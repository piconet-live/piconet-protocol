"""The host's rules' C# generate.py writes (Online.Protocol): HostRules (every rule, All, Alone, Race, Named), the
race's rules record RaceRules (a member a rule the games apply, with a generic Value and With by rule, and Quick
Play's), and RaceWords (a rule's race block word as the game takes it from a match start's rules: what a replay's
header raced). The rule's type (HostRule) and its kinds are Online.Protocol's own (HostRules.cs)."""

GENERATED = "// Generated by protocol/generate.py from protocol/rules.toml. Do not edit."
REACHES = {"alone": "Alone", "together": "Together", "server": "Server", "practice": "Practice"}
KINDS = {"course": "Course", "courses": "Courses", "number": "Number", "switch": "Switch", "range": "Range",
         "choice": "Choice", "delay": "Delay", "machines": "Machines", "pack": "Pack", "text": "Text"}


def text(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def doc(summary, indent="    "):
    """A /// summary, wrapped at 120 characters."""
    lines, line = [], f"{indent}/// <summary>"
    for word in summary.split():
        if len(line) + 1 + len(word) > 120 and line.strip() != "/// <summary>":
            lines.append(line)
            line = f"{indent}///"
        line += ("" if line.endswith("<summary>") else " ") + word
    return lines + [line + "</summary>"]


def value(v):
    return str(v) if type(v) is int else v


def rule_new(r):
    args = [text(r.name), text(r.label), f"RuleReach.{REACHES[r.reach]}", f"RuleKind.{KINDS[r.kind]}"]
    named = []
    if (r.least, r.most, r.step, r.default) != (0, 0, 1, 0):
        args += [value(r.least), value(r.most)]
        if r.step != 1:
            args.append(value(r.step))
        if r.default != 0:
            named.append(f"Default: {value(r.default)}")
    if r.unit:
        named.append(f"Unit: {text(r.unit)}")
    if r.taken is not None:
        named.append(f"Taken: {text(r.taken)}")
    if r.race and r.race.flag:
        named.append(f"Flag: {text(r.race.flag)}")
    if r.setup not in ("flow", "practice"):
        named.append(f"SetupWord: {text(r.setup)}")
    return "new(" + ", ".join(args + named) + ")"


def host_rules(s):
    out = ["", "public static partial class HostRules", "{"]
    for r in s["rules"]:
        if r.cs is None:
            continue
        if r.doc:
            out += doc(r.doc)
        out += [f"    public static HostRule {r.cs} {{ get; }} = {rule_new(r)};", ""]
        if r.default_pack:
            out += doc("The stat pack a race runs on when nothing states another, by the pack's own name: rules.toml's "
                       "default, its one place. A file of protocol/packs carries the name (a protocol test holds it).")
            out += [f"    public const string DefaultStatPack = {text(r.default_pack)};", ""]
    out += doc("Every rule, in the operator's order: the race's, the lobbies' times and limits, the server's own.")
    out += ["    public static IReadOnlyList<HostRule> All { get; } =", "    ["]
    out += [f"        {r.cs if r.cs else rule_new(r)}," for r in s["rules"] if r.reach != "practice"]
    out += ["    ];", ""]
    out += doc("The rules that mean something in a race alone, in order: what a practice shows.")
    out += ["    public static IReadOnlyList<HostRule> Alone { get; } = [" + ", ".join(
        r.cs for r in s["rules"] if r.reach in ("alone", "practice")) + "];", ""]
    out += doc("The rules the games apply, in the operator's order: the members of <see cref=\"RaceRules\"/>, each a "
               "word of the game's race block; a practice's rule is not among them (no server sets it).")
    out += ["    public static IReadOnlyList<HostRule> Race { get; } = [" + ", ".join(
        r.cs for r in s["race"] if r.reach != "practice") + "];", ""]
    out += doc("A rule by its name; null: no such rule.")
    out += ["    public static HostRule? Named(string name) => All.FirstOrDefault(r => r.Name == name);", "}"]
    return out


def member_type(r):
    return "bool" if r.kind == "switch" else "int"


def absent(r):
    return ("true" if r.race.absent else "false") if r.kind == "switch" else str(r.race.absent)


def race_rules(s):
    race = s["race"]
    summary = ("The race's rules the games apply (a match start's <c>setup.rules</c>; protocol/rules.toml, each a word "
               "of the game's race block). " + " ".join(f"{r.race.cs}: {r.race.doc}." for r in race) +
               " A member a match start leaves out is the game's own way, as every recording made before its rule.")
    params = ", ".join(f"{member_type(r)} {r.race.cs} = {absent(r)}" for r in race)
    out = [""] + doc(summary, "") + [f"public sealed record RaceRules({params})", "{"]
    quick = ", ".join(f"HostRules.{r.cs}.Default != 0" if r.kind == "switch" else f"HostRules.{r.cs}.Default"
                      for r in race)
    out += doc("Quick Play's: every rule's default (<see cref=\"HostRule.Default\"/>).")
    out += [f"    public static RaceRules QuickPlay {{ get; }} = new({quick});", ""]
    out += doc("A rule's value as a whole number (a switch: 1 on); <paramref name=\"rule\"/> is one of "
               "<see cref=\"HostRules.Race\"/> (or a practice's).")
    out += ["    public int Value(HostRule rule) => rule?.Name switch", "    {"]
    out += [f"        {text(r.name)} => {r.race.cs}{' ? 1 : 0' if r.kind == 'switch' else ''}," for r in race]
    out += ["        _ => throw new ArgumentException($\"{rule?.Name} is no rule the games apply\", nameof(rule)),",
            "    };", ""]
    out += doc("The rules with one changed (a switch: on unless 0); <paramref name=\"rule\"/> is one of "
               "<see cref=\"HostRules.Race\"/>.")
    out += ["    public RaceRules With(HostRule rule, int value) => rule?.Name switch", "    {"]
    out += [f"        {text(r.name)} => this with {{ {r.race.cs} = value{' != 0' if r.kind == 'switch' else ''} }},"
            for r in race]
    out += ["        _ => throw new ArgumentException($\"{rule?.Name} is no rule the games apply\", nameof(rule)),",
            "    };", "}"]
    return out


def word(r, steps_a_second):
    if r.kind == "switch":
        return f"Flag(rules, {text(r.race.key)}) ? 1u : 0u"
    taken = f"(uint)Math.Clamp(Number(rules, {text(r.race.key)}, {r.race.absent}), {r.race.low}, {r.race.high})"
    if r.race.steps == "seconds":
        return f"{taken} * {steps_a_second}u"
    if r.race.steps == "ms":
        return f"{taken} * {steps_a_second}u / {r.race.per_second}u"
    return taken


def race_words(s):
    steps = s["block"]["steps_a_second"]
    out = [""] + doc("Each rule's word of the game's race block as the game takes it from a match start's "
                     "<c>setup.rules</c> (the game's core: protocol/generated/race_rules.g.h): a number brought into "
                     "its range, as whole steps of the race where it counts time; a member left out, or of another "
                     "kind, is the rule's own way before it. What a replay's header raced.", "")
    out += ["public static class RaceWords", "{"]
    out += doc("The rule's word, from <paramref name=\"rules\"/> (a match start's rules object; any other value: none "
               "of them).")
    out += ["    public static uint Word(HostRule rule, JsonElement rules) => rule?.Name switch", "    {"]
    out += [f"        {text(r.name)} => {word(r, steps)}," for r in s["race"]]
    out += ["        _ => throw new ArgumentException($\"{rule?.Name} is no rule the games apply\", nameof(rule)),",
            "    };", "",
            "    private static double Number(JsonElement rules, string key, double absent) =>",
            "        rules.ValueKind == JsonValueKind.Object && rules.TryGetProperty(key, out var v) &&",
            "        v.ValueKind == JsonValueKind.Number ? v.GetDouble() : absent;", "",
            "    private static bool Flag(JsonElement rules, string key) =>",
            "        rules.ValueKind == JsonValueKind.Object && rules.TryGetProperty(key, out var v) &&",
            "        v.ValueKind == JsonValueKind.True;", "}"]
    return out


def emit(s):
    out = [GENERATED, "#nullable enable", "", "using System.Text.Json;", "", f"namespace {s['codec']['csharp']['namespace']};"]
    out += host_rules(s) + race_rules(s) + race_words(s)
    return "\n".join(out) + "\n"
