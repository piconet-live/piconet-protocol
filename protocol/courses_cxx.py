"""The courses' names as C++ (generated/course_names.g.h): fzgx::courses, for the game's core, which writes a story
stage's name into the game (port/core/src/boot.cpp). Header-only, standard library only, C++17."""

GENERATED = "// Generated by protocol/generate.py from protocol/courses.toml. Do not edit."


def text(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(t):
    out = [GENERATED,
           "// The courses' names as players know them (protocol/courses.toml): the cup courses by the game's course number,",
           "// and the story's chapters that have a name of their own, which the game's own table does not (it has \"---\").",
           "// SPDX-License-Identifier: GPL-3.0-or-later", "", "#pragma once", "", "#include <array>", "", "namespace fzgx::courses",
           "{",
           "// the story's stages: the game's course numbers FIRST_STORY_STAGE on, one a chapter",
           f"inline constexpr int FIRST_STORY_STAGE = {t['first']}, STORY_CHAPTERS = {t['chapters']};",
           "// the longest name, in characters (without the ending zero)",
           f"inline constexpr int LONGEST = {t['longest']};", "",
           "struct Course", "{", "  int course;", "  const char* place;", "  const char* track;", "};",
           f"inline constexpr std::array<Course, {len(t['courses'])}> COURSES = {{{{"]
    out += [f"    {{{c}, {text(p)}, {text(tr)}}}," for c, p, tr in t["courses"]]
    out += ["}};", "", "struct Chapter", "{", "  int chapter;", "  int course;", "  const char* track;", "};",
            f"inline constexpr std::array<Chapter, {len(t['chapters_named'])}> STORY_CHAPTER_NAMES = {{{{"]
    out += [f"    {{{ch}, {c}, {text(tr)}}}," for ch, c, tr in t["chapters_named"]]
    out += ["}};", "",
            "// The name of a story stage that has one of its own; nullptr for every other course.",
            "constexpr const char* StoryName(int course)",
            "{",
            "  for (const Chapter& c : STORY_CHAPTER_NAMES)",
            "    if (c.course == course)",
            "      return c.track;",
            "  return nullptr;",
            "}",
            "}  // namespace fzgx::courses", ""]
    return "\n".join(out)
