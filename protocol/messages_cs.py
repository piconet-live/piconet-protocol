"""The lobby link's schema as C# (generated/LobbySchema.g.cs): the lines of messages.toml (messages.lines) that
tests/dotnet-messages compares with the lines it writes from Online.Protocol's records by reflection, so that a record
and messages.toml cannot differ unseen. Not compiled into Online.Protocol."""

GENERATED = "// Generated by protocol/generate.py from protocol/messages.toml. Do not edit."


def text(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(lines):
    out = [GENERATED,
           "// The lobby link's records as messages.toml has them, one line a member (messages.py's lines): what",
           "// tests/dotnet-messages holds Online.Protocol's records to.",
           "// SPDX-License-Identifier: GPL-3.0-or-later", "",
           "namespace MessageVectors;", "",
           "internal static class LobbySchema", "{",
           "    public static readonly string[] Lines =", "    ["]
    out += [f"        {text(line)}," for line in lines]
    out += ["    ];", "}", ""]
    return "\n".join(out)
