"""The stat pack's C# lists generate.py writes: generated/StatTables.g.cs, the rows of StatPackRules.All (the ranges)
and StatPackConstants.All (the code constants) and the slots' count, as parts of those two classes (the rest of
each: net/src/Online.Protocol/StatPackRules.cs, StatPackConstants.cs)."""
from stats import literal

GENERATED = "// Generated by protocol/generate.py from protocol/stats.toml. Do not edit."
CS_KIND = {"number": "Number", "bytes": "Bytes", "points": "Points"}


def number(value, single):
    text = literal(value, single)
    return "double.MaxValue" if text is None else text


def rule(r):
    named = ([f"ZLeast: {number(r.z_least, True)}"] if r.z_least else []) + \
            ([f"TriedTo: {number(r.tried, True)}"] if r.tried is not None else [])
    return (f'        new(0x{r.at:02X}, StatWordKind.{CS_KIND[r.kind]}, "{r.name}", {number(r.low, True)}, '
            f'{number(r.high, True)}, {"true" if r.below else "false"}{"".join(", " + n for n in named)}),')


def text(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(tables):
    slots = tables.slots
    constants = [f'        new({slot}, "{c.name}", StatConstantKind.{kind}, 0x{stock:08X}, {number(low, False)}, '
                 f'{number(high, False)}, {text(c.what)}),' for c, slot, kind, at, stock, low, high in slots]
    return "\n".join([
        GENERATED,
        "#nullable enable",
        "",
        f"namespace {tables.codec['csharp']['namespace']};",
        "",
        "public static partial class StatPackRules",
        "{",
        "    /// <summary>By offset.</summary>",
        "    public static IReadOnlyList<StatRule> All { get; } =",
        "    [",
        *[rule(r) for r in tables.rules],
        "    ];",
        "}",
        "",
        "public static partial class StatPackConstants",
        "{",
        "    /// <summary>The slots there are.</summary>",
        f"    public const int SlotCount = {len(slots)};",
        "",
        "    /// <summary>By slot.</summary>",
        "    public static IReadOnlyList<StatConstant> All { get; } =",
        "    [",
        *constants,
        "    ];",
        "}",
        ""])
