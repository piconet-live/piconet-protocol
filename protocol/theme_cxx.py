"""The runner's palette (generated/theme_palette.g.h) from the look's tokens (theme.py): every opaque colour as
0xRRGGBB, in fzgx::theme, under its name in capitals. The game window's overlay.h gives them its own names."""

import theme

HEAD = """// Generated by protocol/generate.py from protocol/theme.tokens.json. Do not edit.
// The look's colours, 0xRRGGBB, each under its token's name in capitals (color.on-accent: ON_ACCENT): every colour,
// and every brush of a name no colour has and with no opacity of its own. Header-only, C++17.
// SPDX-License-Identifier: GPL-3.0-or-later

#pragma once

#include <cstdint>

namespace fzgx::theme
{
"""


def emit(tokens):

    lines = [HEAD]
    for name, t in theme.opaque_colours(tokens).items():
        lines.append(f"constexpr std::uint32_t {t.constant} = 0x{t.colour[1:]};  // {t.group}.{name}\n")
    lines.append("}  // namespace fzgx::theme\n")
    return "".join(lines)
