"""The launcher's resources (generated/Theme.g.axaml) from the look's tokens (theme.py): a ResourceDictionary that
Launcher.App's Theme.axaml merges in. Each group's description is a comment above it."""

import theme

HEAD = "<!-- Generated by protocol/generate.py from protocol/theme.tokens.json. Do not edit. -->\n"


def emit(tokens):

    out = [HEAD, '<ResourceDictionary xmlns="https://github.com/avaloniaui"\n'
                 '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">\n']
    group = None
    for t in tokens:
        if t.group != group:
            group = t.group
            out.append(f"  <!-- {group} -->\n")
        key = theme.axaml_key(t)
        if t.group == "color":
            out.append(f'  <Color x:Key="{key}">{t.colour}</Color>\n')
        elif t.group == "brush":
            colour = f"{{StaticResource {theme.axaml_key(next(c for c in tokens if c.group == 'color' and c.name == t.alias))}}}" \
                if t.alias else t.colour
            opacity = "" if t.opacity == 1.0 else f' Opacity="{t.opacity!r}"'
            out.append(f'  <SolidColorBrush x:Key="{key}" Color="{colour}"{opacity} />\n')
        elif t.group == "size":
            out.append(f'  <x:Double x:Key="{key}">{t.number!r}</x:Double>\n')
        elif t.group == "duration":
            out.append(f'  <x:TimeSpan x:Key="{key}">0:0:{t.ms / 1000:g}</x:TimeSpan>\n')
        elif t.group == "easing":
            x1, y1, x2, y2 = (f"{v:g}" for v in t.curve)
            out.append(f'  <SplineEasing x:Key="{key}" X1="{x1}" Y1="{y1}" X2="{x2}" Y2="{y2}" />\n')
        elif t.group == "shadow":
            s = t.shadow
            argb = "#" + s["color"][7:9] + s["color"][1:7]
            out.append(f'  <BoxShadows x:Key="{key}">{s["offsetX"]} {s["offsetY"]} {s["blur"]} {s["spread"]} {argb}</BoxShadows>\n')
    out.append("</ResourceDictionary>\n")
    return "".join(out)
