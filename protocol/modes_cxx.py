"""The game mode system's vocabulary and bytecode as C++ (generated/mode_words.g.h): fzgx::modes, for the runner's
interpreter (port/core/src/mode.cpp). Header-only, standard library only, C++17."""

GENERATED = "// Generated by protocol/generate.py from protocol/modes.toml. Do not edit."


def emit(t):
    api = t["api"]
    out = [GENERATED,
           "// The game mode system's api, its operations and words (protocol/modes.toml; the package: formats.md section 9).",
           "// SPDX-License-Identifier: GPL-3.0-or-later", "", "#pragma once", "", "#include <cstdint>", "",
           f"namespace {t['namespace_cxx']}", "{",
           "// the api this build runs, and its limits (language 11.1)",
           f"inline constexpr int API = {api['number']};"]
    out += [f"inline constexpr int {k.upper()} = {v};" for k, v in api.items() if k != "number"]
    out += ["", "// the bytecode's operations: the byte, then the operands' bytes (big-endian)",
            "enum Op : std::uint8_t", "{"]
    out += [f"  OP_{o['name'].upper()} = {o['code']:#04x},  // {o['doc']}".rstrip(" /,") if o["doc"] else
            f"  OP_{o['name'].upper()} = {o['code']:#04x}," for o in t["ops"]]
    out += ["};", "", "// an operation's size in bytes, operands included; 0: no such operation",
            "constexpr int OpSize(std::uint8_t op)", "{", "  switch (op)", "  {"]
    out += [f"    case OP_{o['name'].upper()}: return {o['size']};" for o in t["ops"]]
    out += ["    default: return 0;", "  }", "}", ""]
    for kind, prefix, what in (("events", "EVENT", "a rule's event"), ("setups", "SETUP", "a setup word"),
                               ("seat_reads", "SEAT", "a read of a seat (OP_SEATREAD)"),
                               ("race_reads", "RACE", "a read of the race (OP_RACEREAD)"),
                               ("actions", "ACTION", "an action (OP_ACTION)")):
        out += [f"// {what}", f"enum {prefix.title()} : std::uint8_t", "{"]
        out += [f"  {prefix}_{e['pascal'].upper()} = {e['id']},  // {e['name']}" for e in t[kind]]
        out += [f"  {prefix}_COUNT = {len(t[kind])},", "};", ""]
    out += ["// the arguments an action pops", "constexpr int ActionArguments(std::uint8_t action)", "{",
            "  switch (action)", "  {"]
    out += [f"    case ACTION_{a['pascal'].upper()}: return {len(a.get('args', []))};" for a in t["actions"]]
    out += ["    default: return -1;", "  }", "}", "",
            "// a continuous event (every step, each seat) or a discrete one", "constexpr bool Continuous(std::uint8_t event)",
            "{", "  switch (event)", "  {"]
    out += [f"    case EVENT_{e['pascal'].upper()}: return {'true' if e['kind'] == 'continuous' else 'false'};"
            for e in t["events"]]
    out += ["    default: return false;", "  }", "}", "",
            "// the names a discrete event binds: 0 none, 1 its seat, 2 its seat and a second value (a seat or an int)",
            "constexpr int EventBinds(std::uint8_t event)", "{", "  switch (event)", "  {"]
    out += [f"    case EVENT_{e['pascal'].upper()}: return {len(e['binds'].split()) if 'binds' in e else 0};"
            for e in t["events"]]
    out += ["    default: return 0;", "  }", "}", "", f"}}  // namespace {t['namespace_cxx']}", ""]
    return "\n".join(out)
