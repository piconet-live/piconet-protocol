"""The launch file's C++ header generate.py writes: the limits, and for each part of the file a function that takes
the part's members the generated reader takes, in the schema's order, into their places, and refuses a member that
is missing where the schema says why. The function is a template over the reader's object (a Part with Flag,
Whole, Number, Words, OneOf, Wholes, Has and Refuse: port/core/src/files_launch_part.h) and its target, so this
header needs nothing of the core. What the reader takes by hand (the objects, the members of a form of their own)
and every rule between members are the core's own (files_launch.cpp). Header-only, standard library only, C++20."""

import re

from board_cxx import comment

GENERATED = "// Generated by protocol/generate.py from protocol/launch.toml. Do not edit."


def text(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def whole(n):
    return f"{n}u"


def number(n):
    return repr(float(n))


def prefix(part):
    return "" if part.name == "File" else snake_upper(part.name) + "_"


def snake_upper(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def constants(s):
    out = [f"inline constexpr std::size_t MAX_BYTES = {s['launch']['max_bytes']};"]
    for part in s["parts"]:
        for m in part.members:
            name = prefix(part) + m.upper
            if m.most_bytes is not None:
                out.append(f"inline constexpr std::size_t {name}_MOST_BYTES = {m.most_bytes};")
            if m.cs is not None and m.type == "whole" and m.cs["write"] != "always":
                out.append(f"inline constexpr std::uint32_t {name}_LOW = {whole(m.low)}, {name}_HIGH = {whole(m.high)};")
    return out


def take(m):
    k, to = text(m.key), f"&t->{m.to}" if m.to else None
    if m.type == "bool":
        return [f"  p.Flag({k}, {to});"]
    if m.type == "whole":
        return [f"  p.Whole({k}, {to}, {whole(m.low)}, {whole(m.high)});"]
    if m.type == "number":
        return [f"  p.Number({k}, {to}, {number(m.low)}, {number(m.high)});"]
    if m.type == "text":
        return [f"  p.Words({k}, {to}{', true' if m.may_be_empty else ''});"]
    if m.type == "one_of":
        return [f"  p.OneOf({k}, {to}, {{{', '.join(text(v) for v in m.values)}}});"]
    return [f"  p.Wholes({k}, {to}, {whole(m.low)}, {whole(m.high)}, {m.least}, {m.most});"]


def reader(part):
    taken = part.read()
    out = [""] + comment(f"{part.name}{'' if part.key is None else ' (' + text(part.key) + ')'}: {part.doc}. "
                         "Takes " + (", ".join(m.key for m in taken) or "nothing") +
                         ("; by hand: " + ", ".join(m.key for m in part.members if m.hand) if any(m.hand for m in part.members) else "") + ".")
    out += ["template <typename P, typename T>", f"void Read{part.name}([[maybe_unused]] P& p, [[maybe_unused]] T* t)", "{"]
    for m in part.members:
        if not m.hand:
            out += take(m)
        if m.missing:
            out.append(f"  if (!p.Has({text(m.key)}))")
            out.append(f"    p.Refuse({text(m.key)}, {text('is missing: ' + m.missing)});")
    return out + ["}"]


def emit(s):
    ns = s["codec"]["cxx"]["namespace"]
    out = [GENERATED, "// The launch file (protocol/launch.toml; formats.md section 2): what the game's reader takes of it.",
           "// SPDX-License-Identifier: GPL-3.0-or-later", "", "#pragma once", "", "#include <cstddef>", "#include <cstdint>",
           "", f"namespace {ns}", "{"]
    out += constants(s)
    for part in s["parts"]:
        out += reader(part)
    out += [f"}}  // namespace {ns}", ""]
    return "\n".join(out)
