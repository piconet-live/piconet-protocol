"""The launch file's C# writer generate.py writes: the limits (LaunchFormat), and for each part the launcher writes a
record of the members it writes, whose ToJson writes them in the schema's `cs_order`, each by its `write` rule
(launch.toml). What a member's value is (a setting's word, a picture the game would take) is the launcher's own
(Launcher.Core GameLaunchFile); the record writes what it is given."""

from launch_cxx import prefix

GENERATED = "// Generated by protocol/generate.py from protocol/launch.toml. Do not edit."
TYPES = {"bool": "bool", "whole": "int", "text": "string", "one_of": "string"}


def pascal(upper):
    return "".join(w.capitalize() for w in upper.split("_"))


def constants(s):
    out = ["", "/// <summary>The launch file's limits (protocol/launch.toml; formats.md section 2).</summary>",
           "public static class LaunchFormat", "{", "    /// <summary>The longest file the game reads.</summary>",
           f"    public const int MaxBytes = {s['launch']['max_bytes']};"]
    for part in s["parts"]:
        for m in part.members:
            name = pascal(prefix(part) + m.upper)
            if m.most_bytes is not None:
                out += [f"    /// <summary>The most bytes of \"{m.key}\" (UTF-8) the game's reader takes.</summary>",
                        f"    public const int {name}MostBytes = {m.most_bytes};"]
            if m.cs is not None and m.type == "whole" and m.cs["write"] != "always":
                out += [f"    /// <summary>The range of \"{m.key}\" the game's reader takes.</summary>",
                        f"    public const int {name}Low = {m.low}, {name}High = {m.high};"]
    return out + ["}"]


def member_type(m):
    if m.type == "object":
        return m.part.cs + "?"
    w = m.cs["write"]
    return TYPES[m.type] + ("?" if w == "set" else "")


def default(m):
    w = m.cs["write"]
    return {"set": " = null", "true": " = false", "false": " = true", "positive": " = 0"}.get(w, "")


def write(m):
    k, name, w = f"\"{m.key}\"", m.cs.get("name"), m.cs["write"]
    if w == "always":
        return [f"        o[{k}] = {m.cs['value']};"]
    if w == "required":
        return [f"        o[{k}] = {name};"]
    if w == "true":
        return [f"        if ({name})", "        {", f"            o[{k}] = true;", "        }"]
    if w == "false":
        return [f"        if (!{name})", "        {", f"            o[{k}] = false;", "        }"]
    if w == "positive":
        return [f"        if ({name} > 0)", "        {", f"            o[{k}] = {name};", "        }"]
    given = name[0].lower() + name[1:]
    value = f"{given}.ToJson()" if m.type == "object" else given
    return [f"        if ({name} is {{ }} {given})", "        {", f"            o[{k}] = {value};", "        }"]


def record(part):
    written = part.written()
    required = [m for m in written if m.cs["write"] == "required"]
    optional = [m for m in written if m.cs["write"] not in ("required", "always")]
    params = [f"{member_type(m)} {m.cs['name']}" for m in required]
    if part.cs_base:
        params.append("JsonObject? Base = null")
    params += [f"{member_type(m)} {m.cs['name']}{default(m)}" for m in optional]
    keys = ", ".join(f"\"{m.key}\"" for m in written)
    out = ["", f"/// <summary>The launch file's part {part.name}" + (f" (\"{part.key}\")" if part.key else "") + f": {part.doc}.",
           f"/// The launcher writes {keys}" + (", after the members of <c>Base</c> as they are" if part.cs_base else "") +
           ".</summary>", f"public sealed record {part.cs}(", "    " + ",\n    ".join(params) + ")", "{",
           "    /// <summary>The part as JSON, its members in the file's order.</summary>", "    public JsonObject ToJson()", "    {"]
    out.append("        var o = Base?.DeepClone().AsObject() ?? [];" if part.cs_base else "        var o = new JsonObject();")
    for m in written:
        out += write(m)
    return out + ["        return o;", "    }", "}"]


def emit(s):
    out = [GENERATED, "#nullable enable", "", "using System.Text.Json.Nodes;", "",
           f"namespace {s['codec']['csharp']['namespace']};"]
    out += constants(s)
    for part in s["parts"]:
        if part.cs is not None:
            out += record(part)
    return "\n".join(out) + "\n"
