"""The replay file's Python reader generate.py writes, for the tools that read recordings (the project's
test tools, not public: the recording comparison and the reports): the constants, the version a race's features
make, and parse/read: a file's parts as far as the file has them, with its steps. Standard library only; judges nothing."""

import replay_py_compact

GENERATED = "# Generated by protocol/generate.py from protocol/replay.toml. Do not edit."


def emit(s):
    v = s["versions"]
    lines = [GENERATED, '"""The replay file (.fzrp): its constants, the version a race\'s features make, and a file\'s parts as far as',
             "the file has them (parse, read). Every number big-endian. It judges nothing: what a tool refuses is its own",
             '(protocol/formats.md section 1)."""', "import lzma", "import struct", "",
             f"MARK = b\"{s['mark']}\"", f"FRAMES_MARK = b\"{s['frames_mark']}\"", f"LINEUP_MARK = b\"{s['lineup_mark']}\"",
             f"RESULTS_MARK = b\"{s['results_mark']}\""]
    for x in v:
        lines.append(f"VERSION_{x['name'].upper()} = {x['number']}  # {x['doc'][:90]}")
    c = s["compact"]
    lines += [f"COMPACT_VERSION = {c['version']}  # the compact file a recording becomes when it ends",
              f"HEADER_MARK = b\"{c['header_mark']}\"", f"INPUTS_MARK = b\"{c['inputs_mark']}\"",
              f"CHECKSUMS_MARK = b\"{c['checksums_mark']}\"", f"FULL_EVERY = {c['full_every']}",
              f"XZ_PRESET = {c['preset']}", f"DICT_MIN = {c['dict_min']}", f"DICT_MAX = {c['dict_max']}",
              f"XZ_MEMLIMIT = {c['memlimit']}", f"MAX_JSON = {s['max_json']}"]
    lines += [f"VERSION_WRITTEN = {s['written']}", "VERSIONS = (" + ", ".join(str(x["number"]) for x in v) + ")",
              f"FEATURES = (" + ", ".join(f"\"{x['feature']}\"" for x in v[1:]) + ")",
              f"HEAD_SIZE = {s['head_size']}", f"FRAMES_SIZE = {s['frames_size']}", f"LINEUP_SIZE = {s['lineup_size']}",
              f"LINEUP_LEAST = {s['lineup_least']}", f"RECORD_SIZE = {s['record_size']}",
              f"CHECKSUM_SIZE = {s['checksum_size']}", "RESULTS_TAIL = 8", f"MAX_BYTES = {s['max_bytes']}",
              f"MAX_STEPS = {s['max_steps']}", f"MAX_SEATS = {s['max_seats']}",
              "HEADER_KEYS = (" + ", ".join(f"\"{m.key}\"" for m in s["header"]) + ")",
              "RESULT_KEYS = (" + ", ".join(f"\"{m.key}\"" for m in s["result"]) + ")",
              "# the lineup's block: (name, offset, count, struct format of one)",
              "LINEUP_FIELDS = (" + ", ".join(f"(\"{f.snake}\", {f.offset}, {f.count or 1}, \"{ {'u8': 'B', 'i16': 'h'}[f.type]}\")"
                                            for f in s["lineup"] if f.type != "pad") + ",)",
              "", "", "def played(version):", "    \"\"\"Whether the game plays a file of this version.\"\"\"",
              "    return version in VERSIONS or version == COMPACT_VERSION", "", "",
              "def version_of(**features):",
              "    \"\"\"The version a race of these features (FEATURES: True or False) is, and the only one its file may be: the",
              "    highest whose feature it holds, else the first.\"\"\"",
              "    unknown = set(features) - set(FEATURES)", "    if unknown:",
              "        raise ValueError(f\"no feature {sorted(unknown)}\")"]
    for x in reversed(v[1:]):
        lines += [f"    if features.get(\"{x['feature']}\"):", f"        return VERSION_{x['name'].upper()}"]
    lines += [f"    return VERSION_{v[0]['name'].upper()}", "", "",
              "def lineup(block):", "    \"\"\"The lineup's block as a dict of its fields (a block shorter than LINEUP_SIZE reads 0 after its end).\"\"\"",
              "    b = bytes(block[:LINEUP_SIZE]).ljust(LINEUP_SIZE, b\"\\0\")", "    out = {}",
              "    for name, at, count, one in LINEUP_FIELDS:",
              "        values = struct.unpack_from(f\">{count}{one}\", b, at)",
              "        out[name] = list(values) if count > 1 else values[0]", "    return out", "", "",
              "class Replay:",
              "    \"\"\"A file's parts, as far as the file has them (each read only when the one before it is whole). header and",
              "    results are the JSON's bytes (None: not in the file); lineup is the block's bytes and lineup_part the bytes",
              "    from the frames' part to the first step; steps is [(the seats' records, the checksum's 4 bytes)] of the",
              "    whole steps; whole says the steps' bytes are whole steps.\"\"\"", "",
              "    def __init__(self):",
              "        self.marked, self.version, self.header_length, self.header = False, 0, 0, None",
              "        self.frames, self.frames_marked, self.mask, self.seat, self.seats = False, False, 0, 0, []",
              "        self.has_lineup, self.lineup_length, self.lineup, self.lineup_part = False, 0, b\"\", b\"\"",
              "        self.results, self.steps_at, self.steps_end, self.steps, self.whole = None, 0, 0, [], False",
              "        self.race_version, self.compact, self.error = 0, False, None", "", "",
              "def parse(data):",
              "    \"\"\"A replay file's bytes, in their parts (Replay). A compact file is read as the file it was made of",
              "    (expand): version and compact say it, race_version is its race's; one that does not read has marked,",
              "    version and error alone.\"\"\"",
              "    if len(data) >= 6 and data[:4] == MARK and struct.unpack_from(\">H\", data, 4)[0] == COMPACT_VERSION:",
              "        try:", "            r = parse(expand(data))", "        except ValueError as e:",
              "            r = Replay()", "            r.marked, r.error = True, str(e)",
              "        r.version, r.compact = COMPACT_VERSION, True",
              "        r.race_version = r.race_version if r.error is None else 0", "        n = len(r.steps)",
              "        r.steps = [(row, Checksum(c, is_full(t, n))) for t, (row, c) in enumerate(r.steps)]",
              "        return r", "    r = Replay()",
              "    if len(data) < HEAD_SIZE or data[:4] != MARK:", "        return r",
              "    r.marked = True", "    r.version, r.header_length = struct.unpack_from(\">HI\", data, 4)",
              "    r.race_version = r.version",
              "    frames_at = HEAD_SIZE + r.header_length", "    if frames_at > len(data):", "        return r",
              "    r.header = bytes(data[HEAD_SIZE:frames_at])", "    if len(data) - frames_at < FRAMES_SIZE:", "        return r",
              "    r.frames, r.frames_marked = True, data[frames_at:frames_at + 4] == FRAMES_MARK",
              "    r.mask, r.seat = struct.unpack_from(\">II\", data, frames_at + 4)",
              "    r.seats = [i for i in range(32) if r.mask >> i & 1]",
              "    frames_end = frames_at + FRAMES_SIZE", "    r.steps_at, r.steps_end = frames_end, len(data)",
              "    if len(data) - frames_end >= RESULTS_TAIL and data[-4:] == RESULTS_MARK:",
              "        length = struct.unpack_from(\">I\", data, len(data) - 8)[0]",
              "        if length + RESULTS_TAIL <= len(data) - frames_end:",
              "            r.steps_end = len(data) - RESULTS_TAIL - length",
              "            r.results = bytes(data[r.steps_end:len(data) - RESULTS_TAIL])",
              "    if r.steps_end - frames_end >= 8 and data[frames_end:frames_end + 4] == LINEUP_MARK:",
              "        r.has_lineup = True", "        r.lineup_length = struct.unpack_from(\">I\", data, frames_end + 4)[0]",
              "        r.steps_at = frames_end + 8 + r.lineup_length",
              "        r.lineup = bytes(data[frames_end + 8:min(r.steps_at, r.steps_end)])",
              "    r.lineup_part = bytes(data[frames_end:min(r.steps_at, r.steps_end)])",
              "    row = len(r.seats) * RECORD_SIZE", "    size = row + CHECKSUM_SIZE",
              "    if r.seats and r.steps_end >= r.steps_at:",
              "        r.steps = [(bytes(data[at:at + row]), Checksum(data[at + row:at + size]))",
              "                   for at in range(r.steps_at, r.steps_end - size + 1, size)]",
              "        r.whole = (r.steps_end - r.steps_at) % size == 0", "    return r", "", "",
              ] + replay_py_compact.CODE.split("\n") + ["",
              "def read(path):", "    \"\"\"The replay file at path, in its parts (Replay).\"\"\"", "    with open(path, \"rb\") as f:",
              "        return parse(f.read())", ""]
    return "\n".join(lines)
