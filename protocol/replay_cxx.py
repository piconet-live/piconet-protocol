"""The replay file's C++ header generate.py writes: the constants (marks, versions, sizes, limits, the JSON members'
keys and ranges), the version a race's features make, the lineup's block and the results' entry as structs, Parse (a
file's parts, as far as the file has them, judged by nobody: each reader keeps its own refusals) and the writer's
parts (the start, the lineup, a step, the results). Header-only, standard library only, C++20."""

from board_cxx import comment

GENERATED = "// Generated by protocol/generate.py from protocol/replay.toml. Do not edit."
TYPES = {"u8": "std::uint8_t", "i16": "std::int16_t", "u16": "std::uint16_t", "u32": "std::uint32_t"}


def upper(name):
    return name.upper()


def mark(text):
    return "{" + ", ".join(f"'{c}'" for c in text) + "}"


def int_type(m):
    if m.low >= 0 and m.high <= 0xFFFFFFFF:
        return "std::uint32_t"
    if m.low >= -0x80000000 and m.high <= 0x7FFFFFFF:
        return "std::int32_t"
    return "std::int64_t"


def result_type(m):
    t = "bool" if m.type == "bool" else int_type(m)
    return f"std::optional<{t}>" if m.null else t


def constants(s):
    out = [f"inline constexpr std::array<char, 4> MARK = {mark(s['mark'])};",
           f"inline constexpr std::array<char, 4> FRAMES_MARK = {mark(s['frames_mark'])};",
           f"inline constexpr std::array<char, 4> LINEUP_MARK = {mark(s['lineup_mark'])};",
           f"inline constexpr std::array<char, 4> RESULTS_MARK = {mark(s['results_mark'])};", ""]
    for v in s["versions"]:
        out += comment(f"version {v['number']}: {v['doc']}")
        out.append(f"inline constexpr std::uint16_t VERSION_{upper(v['name'])} = {v['number']};")
    out += ["inline constexpr std::uint16_t VERSION_WRITTEN = " + str(s["written"]) + ";  // the only one written",
            "", f"inline constexpr std::size_t HEAD_SIZE = {s['head_size']};  // the mark, the version, the header's length",
            f"inline constexpr std::size_t FRAMES_SIZE = {s['frames_size']};  // the mark, the mask, the seat",
            f"inline constexpr std::size_t LINEUP_SIZE = {s['lineup_size']};  // the block, after its mark and length",
            f"inline constexpr std::size_t LINEUP_LEAST = {s['lineup_least']};  // the shortest block a playback reads",
            "inline constexpr std::size_t LINEUP_PART = 8 + LINEUP_SIZE;",
            f"inline constexpr std::size_t RECORD_SIZE = {s['record_size']};  // a seat's control record (relay.toml)",
            f"inline constexpr std::size_t CHECKSUM_SIZE = {s['checksum_size']};",
            "inline constexpr std::size_t RESULTS_TAIL = 8;  // after the results' JSON: its length, the mark",
            f"inline constexpr std::size_t MAX_BYTES = {s['max_bytes']};",
            f"inline constexpr std::size_t MAX_STEPS = {s['max_steps']};",
            f"inline constexpr std::size_t MAX_JSON = {s['max_json']};",
            f"inline constexpr std::uint32_t MAX_SEATS = {s['max_seats']};", "",
            "// Whether a reader of the game plays a file of this version.",
            "constexpr bool Played(std::uint32_t version)", "{",
            "  return " + " || ".join(f"version == {v['number']}" for v in s["versions"]) + ";", "}", "",
            "// What a race holds that a version says (replay.toml's features).", "struct Features", "{"]
    out += [f"  bool {v['feature']} = false;  // {v['name']}" for v in s["versions"][1:]]
    out += ["};", "", "// The version a race of these features is written as, and the only one its file may be: the highest whose",
            "// feature it holds, else the first.", "constexpr std::uint16_t VersionOf(const Features& f)", "{"]
    for v in reversed(s["versions"][1:]):
        out.append(f"  if (f.{v['feature']})")
        out.append(f"    return VERSION_{upper(v['name'])};")
    out += [f"  return VERSION_{upper(s['versions'][0]['name'])};", "}"]
    return out


def members(s):
    out = []
    for part, ns in (("header", "header"), ("result", "result")):
        out += ["", f"// The {part}'s JSON members: each key, and a whole number's range and default.", f"namespace {ns}", "{"]
        for m in s[part]:
            line = f"inline constexpr const char* {upper(m.snake)} = \"{m.key}\";"
            out.append(line + (f"  // {m.doc}" if m.doc and len(line) + len(m.doc) < 116 else ""))
            if m.type == "int":
                t = int_type(m) if part == "result" else "std::uint32_t"
                out.append(f"inline constexpr {t} {upper(m.snake)}_LOW = {m.low};")
                out.append(f"inline constexpr {t} {upper(m.snake)}_HIGH = {m.high}{'u' if t == 'std::uint32_t' else ''};")
                if m.default is not None:
                    out.append(f"inline constexpr {t} {upper(m.snake)}_DEFAULT = {m.default};")
        out.append(f"}}  // namespace {ns}")
    return out


def lineup(s):
    out = [""] + comment(f"The lineup's block: {s['lineup_doc']}.") + ["struct Lineup", "{"]
    for f in s["lineup"]:
        if f.type == "pad":
            continue
        t = TYPES[f.type]
        line = f"  std::array<{t}, {f.count}> {f.snake}{{}};" if f.count else f"  {t} {f.snake} = 0;"
        out.append(line + (f"  // {f.doc}" if f.doc and len(line) + len(f.doc) < 116 else ""))
    out += ["};", "", "// The block's first `size` bytes (at most LINEUP_SIZE; the rest stays 0).",
            "inline Lineup DecodeLineup(const std::uint8_t* block, std::size_t size)", "{",
            "  std::array<std::uint8_t, LINEUP_SIZE> b{};",
            "  std::memcpy(b.data(), block, size < LINEUP_SIZE ? size : LINEUP_SIZE);", "  Lineup l;"]
    for f in s["lineup"]:
        if f.type == "pad":
            continue
        one = {"u8": "b[{at}]", "i16": "static_cast<std::int16_t>(detail::Get16(b.data() + {at}))"}[f.type]
        size = f.size // (f.count or 1)
        if f.count:
            out.append(f"  for (std::size_t i = 0; i < {f.count}; ++i)")
            out.append(f"    l.{f.snake}[i] = {one.format(at=f'{f.offset} + i * {size}')};")
        else:
            out.append(f"  l.{f.snake} = {one.format(at=f.offset)};")
    out += ["  return l;", "}", "", "// The lineup's part of the file: its mark, its length, the block.",
            "inline std::vector<std::uint8_t> EncodeLineup(const Lineup& l)", "{",
            "  std::vector<std::uint8_t> out(LINEUP_PART, 0);",
            "  std::memcpy(out.data(), LINEUP_MARK.data(), 4);",
            "  detail::Put32(out.data() + 4, static_cast<std::uint32_t>(LINEUP_SIZE));",
            "  std::uint8_t* b = out.data() + 8;"]
    for f in s["lineup"]:
        if f.type == "pad":
            continue
        size = f.size // (f.count or 1)
        one = {"u8": "b[{at}] = {v};", "i16": "detail::Put16(b + {at}, static_cast<std::uint16_t>({v}));"}[f.type]
        if f.count:
            out.append(f"  for (std::size_t i = 0; i < {f.count}; ++i)")
            out.append("    " + one.format(at=f"{f.offset} + i * {size}", v=f"l.{f.snake}[i]"))
        else:
            out.append("  " + one.format(at=f.offset, v=f"l.{f.snake}"))
    return out + ["  return out;", "}"]


def results(s):
    out = ["", "// A racer's entry of the results.", "struct Result", "{"]
    for m in s["result"]:
        init = "" if m.null else (" = false" if m.type == "bool" else " = 0")
        line = f"  {result_type(m)} {m.snake}{init};"
        out.append(line + (f"  // {m.doc}" if m.doc else ""))
    out += ["};", "", f"// The results' JSON, as the file holds it: {{\"{s['results_list']}\":[entry,...]}}, members in the schema's order.",
            "inline std::string ResultsJson(const std::vector<Result>& results)", "{",
            f"  std::string json = \"{{\\\"{s['results_list']}\\\":[\";",
            "  for (std::size_t i = 0; i < results.size(); ++i)", "  {", "    const Result& r = results[i];",
            "    json += i == 0 ? \"{\" : \",{\";"]
    for i, m in enumerate(s["result"]):
        key = ("," if i else "") + f"\\\"{m.key}\\\":"
        if m.type == "bool":
            value = f"(r.{m.snake} ? \"true\" : \"false\")"
        elif m.null:
            value = f"(r.{m.snake} ? std::to_string(*r.{m.snake}) : std::string(\"null\"))"
        else:
            value = f"std::to_string(r.{m.snake})"
        out.append(f"    json += \"{key}\";")
        out.append(f"    json += {value};")
    return out + ["    json += \"}\";", "  }", "  return json + \"]}\";", "}"]


def parts():
    return ["", "// A file's parts, as far as the file has them (each read only when the one before it is whole). It judges",
            "// nothing: which version, which seats, whether a lineup or a whole step is needed are each reader's own.",
            "struct Parts", "{",
            "  bool marked = false;          // HEAD_SIZE bytes, the first four the mark",
            "  std::uint16_t version = 0;",
            "  std::uint32_t header_length = 0;",
            "  bool header = false;          // the file holds the whole header (at HEAD_SIZE)",
            "  bool frames = false;          // the frames' part is there (FRAMES_SIZE bytes after the header)",
            "  bool frames_marked = false;   // and begins with its mark",
            "  std::uint32_t mask = 0;",
            "  std::uint32_t seat = 0;",
            "  bool lineup = false;          // a lineup's mark and length after the frames' part",
            "  std::uint32_t lineup_length = 0;",
            "  std::size_t lineup_at = 0;    // the block's first byte",
            "  bool results = false;         // the results' JSON, its length and mark end the file",
            "  std::size_t results_at = 0;",
            "  std::uint32_t results_length = 0;",
            "  std::size_t steps_at = 0;     // the first step's first byte (after the lineup, or the frames' part)",
            "  std::size_t steps_end = 0;    // the results' first byte, or the file's end",
            "",
            "  std::size_t HeaderAt() const { return HEAD_SIZE; }",
            "  std::size_t FramesAt() const { return HEAD_SIZE + std::size_t{header_length}; }",
            "  std::size_t Seats() const { return static_cast<std::size_t>(std::popcount(mask)); }",
            "  std::size_t Row() const { return Seats() * RECORD_SIZE; }  // a step's records",
            "  std::size_t StepSize() const { return Row() + CHECKSUM_SIZE; }",
            "  std::size_t StepBytes() const { return steps_end > steps_at ? steps_end - steps_at : 0; }",
            "  std::size_t Steps() const { return Seats() == 0 ? 0 : StepBytes() / StepSize(); }  // whole steps",
            "  // the steps' bytes are whole steps (none at all included)",
            "  bool Whole() const { return Seats() != 0 && steps_end >= steps_at && StepBytes() % StepSize() == 0; }",
            "  std::size_t StepAt(std::size_t step) const { return steps_at + step * StepSize(); }",
            "};", "",
            "inline Parts Parse(const std::uint8_t* data, std::size_t size)", "{", "  Parts p;",
            "  if (size < HEAD_SIZE || std::memcmp(data, MARK.data(), 4) != 0)", "    return p;",
            "  p.marked = true;", "  p.version = detail::Get16(data + 4);", "  p.header_length = detail::Get32(data + 6);",
            "  const std::size_t frames_at = p.FramesAt();", "  p.header = frames_at <= size;",
            "  if (!p.header || size - frames_at < FRAMES_SIZE)", "    return p;",
            "  p.frames = true;", "  p.frames_marked = std::memcmp(data + frames_at, FRAMES_MARK.data(), 4) == 0;",
            "  p.mask = detail::Get32(data + frames_at + 4);", "  p.seat = detail::Get32(data + frames_at + 8);",
            "  const std::size_t frames_end = frames_at + FRAMES_SIZE;",
            "  p.steps_at = frames_end;", "  p.steps_end = size;",
            "  if (size - frames_end >= RESULTS_TAIL && std::memcmp(data + size - 4, RESULTS_MARK.data(), 4) == 0)", "  {",
            "    const std::uint32_t length = detail::Get32(data + size - 8);",
            "    if (std::size_t{length} + RESULTS_TAIL <= size - frames_end)", "    {",
            "      p.results = true;", "      p.results_length = length;",
            "      p.results_at = size - RESULTS_TAIL - length;", "      p.steps_end = p.results_at;", "    }", "  }",
            "  if (p.steps_end - frames_end >= 8 && std::memcmp(data + frames_end, LINEUP_MARK.data(), 4) == 0)", "  {",
            "    p.lineup = true;", "    p.lineup_length = detail::Get32(data + frames_end + 4);",
            "    p.lineup_at = frames_end + 8;", "    p.steps_at = p.lineup_at + std::size_t{p.lineup_length};", "  }",
            "  return p;", "}", "",
            "// The file's first parts, as the writer starts it: the head (VERSION_WRITTEN), the header, the frames' part.",
            "// (EncodeStartAs: another version, for the round trip of older files only.)",
            "inline std::vector<std::uint8_t> EncodeStartAs(std::uint16_t version, std::string_view header, std::uint32_t mask,",
            "                                               std::uint32_t seat)", "{",
            "  std::vector<std::uint8_t> out(HEAD_SIZE + header.size() + FRAMES_SIZE);",
            "  std::memcpy(out.data(), MARK.data(), 4);", "  detail::Put16(out.data() + 4, version);",
            "  detail::Put32(out.data() + 6, static_cast<std::uint32_t>(header.size()));",
            "  std::memcpy(out.data() + HEAD_SIZE, header.data(), header.size());",
            "  std::uint8_t* f = out.data() + HEAD_SIZE + header.size();",
            "  std::memcpy(f, FRAMES_MARK.data(), 4);", "  detail::Put32(f + 4, mask);", "  detail::Put32(f + 8, seat);",
            "  return out;", "}", "",
            "inline std::vector<std::uint8_t> EncodeStart(std::string_view header, std::uint32_t mask, std::uint32_t seat)", "{",
            "  return EncodeStartAs(VERSION_WRITTEN, header, mask, seat);", "}", "",
            "// A step: the player seats' records (Row() bytes), then its checksum.",
            "inline void EncodeStep(std::vector<std::uint8_t>& out, const std::uint8_t* row, std::size_t row_size, std::uint32_t checksum)", "{",
            "  out.insert(out.end(), row, row + row_size);",
            "  const std::size_t at = out.size();", "  out.resize(at + CHECKSUM_SIZE);", "  detail::Put32(out.data() + at, checksum);", "}", "",
            "// The results' part: the JSON, its length, the mark (the file's last bytes).",
            "inline std::vector<std::uint8_t> EncodeResults(std::string_view json)", "{",
            "  std::vector<std::uint8_t> out(json.begin(), json.end());", "  out.resize(json.size() + RESULTS_TAIL);",
            "  detail::Put32(out.data() + json.size(), static_cast<std::uint32_t>(json.size()));",
            "  std::memcpy(out.data() + json.size() + 4, RESULTS_MARK.data(), 4);", "  return out;", "}"]


def helpers():
    return ["", "namespace detail", "{",
            "inline std::uint16_t Get16(const std::uint8_t* p) { return static_cast<std::uint16_t>(p[0] << 8 | p[1]); }",
            "inline std::uint32_t Get32(const std::uint8_t* p)", "{",
            "  return std::uint32_t{p[0]} << 24 | std::uint32_t{p[1]} << 16 | std::uint32_t{p[2]} << 8 | p[3];", "}",
            "inline void Put16(std::uint8_t* p, std::uint16_t v)", "{",
            "  p[0] = static_cast<std::uint8_t>(v >> 8);", "  p[1] = static_cast<std::uint8_t>(v);", "}",
            "inline void Put32(std::uint8_t* p, std::uint32_t v)", "{",
            "  p[0] = static_cast<std::uint8_t>(v >> 24);", "  p[1] = static_cast<std::uint8_t>(v >> 16);",
            "  p[2] = static_cast<std::uint8_t>(v >> 8);", "  p[3] = static_cast<std::uint8_t>(v);", "}",
            "}  // namespace detail"]


def emit(s):
    ns = s["codec"]["cxx"]["namespace"]
    lines = [GENERATED,
             "// The replay file (.fzrp): its constants, the version a race's features make, the lineup and a result,",
             "// a file's parts (Parse) and the writer's parts. Every number big-endian. What each reader refuses is",
             "// its own (protocol/formats.md section 1).",
             "// SPDX-License-Identifier: GPL-3.0-or-later", "", "#pragma once", "",
             "#include <array>", "#include <bit>", "#include <cstddef>", "#include <cstdint>", "#include <cstring>",
             "#include <optional>", "#include <string>", "#include <string_view>", "#include <vector>", "",
             f"namespace {ns}", "{"]
    lines += constants(s) + members(s) + helpers() + lineup(s) + results(s) + parts()
    lines += ["", f"}}  // namespace {ns}", ""]
    return "\n".join(lines)
