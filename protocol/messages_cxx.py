"""The lobby link's messages as C++ (generated/lobby_messages.g.h): fzgx::net::lobby, a struct a record, an enum class
an enum, `std::variant`s of the client's and the server's messages, and their JSON both ways on cxx/json_wire.h
(System.Text.Json's writing and reading, byte for byte). Header-only, standard library only, C++17. For the native
program's lobby client (port/native/net in the runner)."""
import json

GENERATED = "// Generated by protocol/generate.py from protocol/messages.toml. Do not edit."

PLAIN = {"string": "std::string", "int": "std::int32_t", "uint": "std::uint32_t", "long": "std::int64_t",
         "byte": "std::uint8_t", "bool": "bool", "float": "float", "double": "double", "time": "Time"}
UNDERLYING = {"int": ("std::int32_t", -(1 << 31), (1 << 31) - 1), "byte": ("std::uint8_t", 0, 255)}
KEYWORDS = set("""alignas alignof and and_eq asm auto bitand bitor bool break case catch char char8_t char16_t char32_t
class compl concept const consteval constexpr constinit const_cast continue co_await co_return co_yield decltype
default delete do double dynamic_cast else enum explicit export extern false float for friend goto if inline int long
mutable namespace new noexcept not not_eq nullptr operator or or_eq private protected public register reinterpret_cast
requires return short signed sizeof static static_assert static_cast struct switch template this thread_local throw
true try typedef typeid typename union unsigned using virtual void volatile wchar_t while xor xor_eq""".split())


def ident(name):
    """A member's C++ name: its JSON name, with "_" after a C++ keyword (`default_`, `or_`)."""
    return name + "_" if name in KEYWORDS else name


def cxx_type(t):
    if t.kind == "list":
        base = f"std::vector<{cxx_type(t.element)}>"
    elif t.kind == "map":
        base = "Map"
    elif t.kind == "plain":
        base = PLAIN[t.name]
    else:
        base = t.name
    return f"std::optional<{base}>" if t.nullable else base


def held(t):
    """A member C# holds as a reference and that is no "?": null on the wire is kept as its bit of wire_absent."""
    return not t.nullable and not t.is_value()


def literal(s):
    out = '"'
    for b in s.encode("utf-8"):
        c = chr(b)
        out += {'"': '\\"', "\\": "\\\\", "\n": "\\n", "\t": "\\t", "\r": "\\r"}.get(c, c) if 0x20 <= b < 0x7F or c in "\n\t\r" else f"\\x{b:02X}\"\""
    return out + '"'


def initializer(m):
    """The member's default initializer (C#'s constructor default), or a value's zero."""
    t, d = m["type"], m["default"]
    if d is not None and d != "null":
        value = json.loads(d)
        if isinstance(value, bool):
            return " = true" if value else " = false"
        if isinstance(value, str):
            return " = " + (f"{t.name}::{value}" if t.kind == "enum" else literal(value))
        return f" = {value}"
    if not t.nullable and (t.kind == "enum" or (t.kind == "plain" and t.name not in ("string", "time"))):
        return " = false" if t.name == "bool" else " = {}"
    return ""


def read_inner(t, target, holes_bit, record):
    """The expression that reads value `v` into `target` (a type that is no "?")."""
    if t.kind == "list":
        if t.element.is_value():
            return f"Get(v, {target})"
        return (f"[&] {{ bool holes = false; out.wire_holes &= ~{record}::Bit::{holes_bit}; const bool ok = Get(v, {target}, &holes); "
                f"if (holes) out.wire_holes |= {record}::Bit::{holes_bit}; return ok; }}()")
    if t.kind == "map":
        return f"json_wire::GetMap(v, {target})"
    return f"Get(v, {target})"


def read_member(m, record):
    t, name = m["type"], ident(m["name"])
    if held(t):
        inner = read_inner(t, "out." + name, name, record).replace("Get(v, ", "Get(y, ").replace("GetMap(v, ", "GetMap(y, ")
        return (f"json_wire::Held(v, out.{name}, out.wire_absent, {record}::Bit::{name}, "
                f"[&](const json_wire::Value& y, {cxx_type(t)}&) {{ return {inner}; }})")
    if t.nullable and t.kind == "list":
        plain = type(t)("list", "list", t.element, False)
        return (f"(v.kind == json_wire::Value::Kind::Null ? (out.{name}.reset(), true) : "
                f"(out.{name}.emplace(), {read_inner(plain, '*out.' + name, name, record)}))")
    if t.kind == "map":
        return f"json_wire::GetMap(v, out.{name})"
    return f"Get(v, out.{name})"


def write_member(m, record):
    t, name, key = m["type"], ident(m["name"]), m["name"]
    put = "json_wire::PutMap" if t.kind == "map" else "Put"
    if m["written"] is not None:
        if t.nullable:
            return [f"  if (const auto w = {m['written']}; w)", "  {", f"    json_wire::Key(o, first, \"{key}\");",
                    f"    {put}(o, *w);", "  }"]
        return ["  {", f"    const {cxx_type(t)} w = {m['written']};", f"    json_wire::Key(o, first, \"{key}\");",
                f"    {put}(o, w);", "  }"]
    if t.nullable:
        cond, value = f"v.{name}", f"*v.{name}"
    elif held(t):
        cond, value = f"!(v.wire_absent & {record}::Bit::{name})", f"v.{name}"
    elif m["omit"] == "default":
        cond, value = (f"v.{name}" if t.name == "bool" else f"v.{name} != {cxx_type(t)}{{}}"), f"v.{name}"
    else:
        return [f"  json_wire::Key(o, first, \"{key}\");", f"  {put}(o, v.{name});"]
    return [f"  if ({cond})", "  {", f"    json_wire::Key(o, first, \"{key}\");", f"    {put}(o, {value});", "  }"]


def emit_enum(e):
    under, least, most = UNDERLYING[e["underlying"]]
    name = e["name"]
    out = [f"// {'written by name' if e['named'] else 'written as its number'} (any {e['underlying']} is one)",
           f"enum class {name} : {under}", "{"]
    out += [f"  {v} = {i}," for i, v in enumerate(e["values"])]
    out += ["};", ""]
    names = ", ".join(f'"{v}"' for v in e["values"])
    out += [f"inline constexpr std::string_view k{name}Names[] = {{{names}}};", ""]
    out += [f"inline bool Get(const json_wire::Value& v, {name}& out)", "{", "  std::int64_t n = 0;"]
    if e["named"]:
        out += [f"  if (!json_wire::GetNamedEnum(v, k{name}Names, {len(e['values'])}, {least}, {most}, n))"]
    else:
        out += [f"  if (!json_wire::GetNumberEnum(v, {least}, {most}, n))"]
    out += ["    return false;", f"  out = static_cast<{name}>(n);", "  return true;", "}", ""]
    out += [f"inline void Put(json_wire::Out& o, {name} v)", "{"]
    if e["named"]:
        out += [f"  const auto n = static_cast<std::int64_t>(v);",
                f"  if (n >= 0 && n < {len(e['values'])})",
                f"    json_wire::PutString(o, k{name}Names[n]);", "  else",
                f"    json_wire::Put(o, n);"]
    else:
        out += ["  json_wire::Put(o, static_cast<std::int64_t>(v));"]
    out += ["}", ""]
    return out


def emit_record(r):
    name, members = r["name"], r["members"]
    read = [m for m in members if m["written"] is None]
    absent = [i for i, m in enumerate(members) if m["written"] is None and held(m["type"]) and m["default"] is None]
    what = {"client": f"the client's message \"{r['type']}\"", "server": f"the server's message \"{r['type']}\"",
            "lan": "the LAN announcement (UDP 47800)", "status": "the server's public status (GET /api/status)"}
    out = [f"// {what.get(r['root'], 'a part of a message')} (Online.Protocol {name})", f"struct {name}", "{"]
    for m in members:
        note = "  // written only, from the others" if m["written"] is not None else ""
        if m["written"] is None:
            out.append(f"  {cxx_type(m['type'])} {ident(m['name'])}{initializer(m)};")
        else:
            out.append(f"  // \"{m['name']}\": written only ({m['written']}){note and ''}")
    out += ["", "  // one bit a member, of wire_absent (a member that is no \"?\" read as null or left out: C# holds null; it",
            "  // is then not written) and of wire_holes (a list that held null items, dropped)", "  struct Bit", "  {"]
    out += [f"    static constexpr std::uint32_t {ident(m['name'])} = 1u << {i};" for i, m in enumerate(members)]
    out += ["  };", "  static constexpr std::uint32_t kAbsentAtStart = " +
            (" | ".join(f"Bit::{ident(members[i]['name'])}" for i in absent) if absent else "0") + ";",
            "  std::uint32_t wire_absent = 0;", "  std::uint32_t wire_holes = 0;", "};", ""]
    # reading
    out += [f"inline bool Get(const json_wire::Value& x, {name}& out, std::size_t from = 0)", "{",
            "  if (x.kind != json_wire::Value::Kind::Object)", "    return false;", f"  out = {name}{{}};",
            f"  out.wire_absent = {name}::kAbsentAtStart;"]
    if read:
        out += ["  static constexpr std::string_view kNames[] = {" + ", ".join(f'"{m["name"]}"' for m in read) + "};",
                "  for (std::size_t i = from; i < x.members.size(); ++i)", "  {",
                "    const json_wire::Value& v = x.members[i].second;", "    switch (json_wire::Find(x.members[i].first, kNames))",
                "    {"]
        for i, m in enumerate(read):
            out += [f"    case {i}:", f"      if (!{read_member(m, name)})", "        return false;", "      break;"]
        out += ["    default:", "      break;   // a member it does not know, or one written only", "    }", "  }"]
    else:
        out += ["  (void)from;"]
    out += ["  return true;", "}", ""]
    # writing
    out += [f"inline void Put(json_wire::Out& o, const {name}& v, std::string_view type = {{}})", "{",
            "  o.text += '{';", "  bool first = true;", "  if (!type.empty())", "  {",
            "    json_wire::Key(o, first, \"type\");", "    json_wire::PutString(o, type);", "  }"]
    for m in members:
        out += write_member(m, name)
    if not members:
        out += ["  (void)v;"]
    out += ["  o.text += '}';", "}", ""]
    return out


def emit_family(root, family, records):
    msgs = [r for r in records if r["root"] == root]
    alts = ",\n    ".join(r["name"] for r in msgs)
    out = [f"// Every message of the {root} side, by its \"type\".", f"using {family} = std::variant<\n    {alts}>;",
           f"inline constexpr std::string_view k{family}Types[] = {{" + ", ".join(f'"{r["type"]}"' for r in msgs) + "};", "",
           f"// A {root} message's JSON, as C# writes it; \"\" when it cannot be written (a float that is not finite).",
           f"inline std::string Encode(const {family}& m)", "{", "  json_wire::Out o;",
           f"  std::visit([&](const auto& x) {{ Put(o, x, k{family}Types[m.index()]); }}, m);",
           "  return o.ok ? std::move(o.text) : std::string{};", "}", ""]
    for r in msgs:
        out += [f"inline std::string Encode(const {r['name']}& m)", "{", "  json_wire::Out o;",
                f"  Put(o, m, \"{r['type']}\");", "  return o.ok ? std::move(o.text) : std::string{};", "}", ""]
    fn = "DecodeClient" if root == "client" else "DecodeServer"
    out += [f"// The {root} message of a JSON text, as C# reads it; nothing when it reads none.",
            f"inline std::optional<{family}> {fn}(std::string_view text)", "{", "  json_wire::Value x;",
            "  std::string_view type;", "  if (!json_wire::Parse(text, x) || !json_wire::Discriminator(x, type))",
            "    return std::nullopt;"]
    for r in msgs:
        out += [f"  if (type == \"{r['type']}\")", "  {", f"    {r['name']} m;", "    if (!Get(x, m, 1))",
                "      return std::nullopt;", f"    return {family}{{std::move(m)}};", "  }"]
    out += ["  return std::nullopt;", "}", ""]
    return out


def emit_document(r):
    name = r["name"]
    return [f"inline std::string Encode(const {name}& m)", "{", "  json_wire::Out o;", "  Put(o, m);",
            "  return o.ok ? std::move(o.text) : std::string{};", "}", "",
            f"inline std::optional<{name}> Decode{name}(std::string_view text)", "{", "  json_wire::Value x;",
            f"  {name} m;", "  if (!json_wire::Parse(text, x) || !Get(x, m))", "    return std::nullopt;", "  return m;", "}", ""]


def emit(table, ordered):
    link = table["link"]
    out = [GENERATED,
           "// The lobby link (protocol/messages.toml): the coordinator's WebSocket messages and the two documents read",
           "// with the same JSON, as Online.Protocol's records are written and read by System.Text.Json, on",
           "// protocol/cxx/json_wire.h. A member that is no \"?\" in C# and is a text, a list, a map or a record can be null",
           "// on the wire (C# then holds null): such a member read as null or left out has its bit in `wire_absent` and",
           "// is not written again; a list's null items are dropped and noted in `wire_holes`. Names: messages.toml's,",
           "// a C++ keyword with \"_\" after it.",
           "// SPDX-License-Identifier: GPL-3.0-or-later", "", "#pragma once", "",
           "#include <algorithm>", "#include <cstddef>", "#include <cstdint>", "#include <optional>", "#include <string>",
           "#include <string_view>", "#include <utility>", "#include <variant>", "#include <vector>", "",
           "#include \"../cxx/json_wire.h\"", "", "namespace fzgx::net::lobby", "{",
           "using json_wire::Get;", "using json_wire::Map;", "using json_wire::Put;", "using json_wire::Time;",
           "using json_wire::Wrap;", "",
           "// ControlProtocol's numbers: the protocol version a hello names, the WebSocket's path, how often each side",
           "// pings, the chat's channels",
           f"inline constexpr int kVersion = {link['version']};",
           f"inline constexpr std::string_view kPath = {literal(link['path'])};",
           f"inline constexpr int kKeepAliveSeconds = {link['keep_alive_seconds']};",
           f"inline constexpr std::string_view kGlobalChannel = {literal(link['global_channel'])};",
           f"inline constexpr std::string_view kLobbyChannel = {literal(link['lobby_channel'])};", ""]
    for e in table["enums"]:
        out += emit_enum(e)
    for r in ordered:
        out += emit_record(r)
    out += emit_family("client", "ClientMessage", table["records"])
    out += emit_family("server", "ServerMessage", table["records"])
    for r in table["records"]:
        if r["root"] in ("lan", "status"):
            out += emit_document(r)
    out += ["}  // namespace fzgx::net::lobby", ""]
    return "\n".join(out)
