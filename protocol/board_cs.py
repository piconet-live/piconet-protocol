"""The status board's C# view generate.py writes: the constants, the enums and flags, a class for every seqlock
block, a struct for every record, and BoardView, the board's memory read and written through a pointer (every word a
volatile access, a seqlock block as one group): what the launcher maps (Launcher.Core). Every type's name begins
with the codec's prefix, so that none stands in the way of a launcher type."""

from board import snake

GENERATED = "// <auto-generated>Generated by protocol/generate.py from protocol/board.toml. Do not edit.</auto-generated>"
TYPES = {"u8": "byte", "u16": "ushort", "u32": "uint", "u64": "ulong", "i32": "int", "f32": "float"}


def doc(text, indent=""):
    out, line = [], f"{indent}/// <summary>"
    for word in text.replace("&", "and").replace("<", "less than").split():
        if len(line) + 1 + len(word) > 120:
            out.append(line)
            line = f"{indent}///"
        line += " " + word
    return out + [line + "</summary>"]


class Names:
    def __init__(self, board):
        self.prefix = board["codec"]["csharp"].get("prefix", "")

    def __call__(self, name):
        return self.prefix + name


def value_type(f, n):
    if f.record:
        return f"{n(f.record.name)}[]"
    if f.type == "bytes":
        return "byte[]"
    if f.enum:
        return n(f.enum)
    return TYPES[f.type]


def member(f, n):
    if f.record:
        return f"    public {value_type(f, n)} {f.name} = new {n(f.record.name)}[{f.count}];"
    if f.type == "bytes":
        return f"    public byte[] {f.name} = new byte[{f.size}];"
    return f"    public {value_type(f, n)} {f.name};"


def load(f, at, target, n):
    if f.record:
        return [f"for (var i = 0; i < {f.count}; i++)", "{",
                f"    Load{f.record.name}({at} + i * {f.record.size}, ref {target}[i]);", "}"]
    if f.type == "bytes":
        return [f"for (var i = 0; i < {f.size // 4}; i++)", "{",
                f"    BinaryPrimitives.WriteUInt32LittleEndian({target}.AsSpan(i * 4), Volatile.Read(ref *(uint*)(_at + {at} + i * 4)));", "}"]
    word = f"Volatile.Read(ref *({TYPES[f.type]}*)(_at + {at}))"
    if f.enum:
        return [f"{target} = ({n(f.enum)}){word};"]
    return [f"{target} = {word};"]


def store(f, at, source, n):
    if f.record:
        return [f"for (var i = 0; i < {f.count}; i++)", "{", f"    Store{f.record.name}({at} + i * {f.record.size}, in {source}[i]);", "}"]
    if f.type == "bytes":
        return [f"for (var i = 0; i < {f.size // 4}; i++)", "{",
                f"    Volatile.Write(ref *(uint*)(_at + {at} + i * 4), BinaryPrimitives.ReadUInt32LittleEndian({source}.AsSpan(i * 4)));", "}"]
    if f.enum:
        return [f"Volatile.Write(ref *({TYPES[f.type]}*)(_at + {at}), ({TYPES[f.type]}){source});"]
    return [f"Volatile.Write(ref *({TYPES[f.type]}*)(_at + {at}), {source});"]


def indent(lines, by):
    return [by + line if line else line for line in lines]


def emit(board, enums, flags, records, blocks):
    n = Names(board)
    c = board["codec"]["csharp"]
    out = [GENERATED, "#nullable enable", "using System.Buffers.Binary;", "using System.Threading;", "",
           f"namespace {c['namespace']};", ""]
    out += doc("The status board's layout (protocol/board.toml; protocol/formats.md section 8): where each block and each "
               "plain word is, from the board's first byte.")
    out += [f"public static class {c['class']}", "{",
            f"    /// <summary>\"{board['magic']}\": the board's first four bytes.</summary>",
            f"    public const uint Magic = 0x{board['magic_word']:08X};",
            f"    public const uint Version = {board['version']};", f"    public const int Size = {board['size']};"]
    for b in blocks:
        out.append(f"    public const int {b.name} = {b.offset};")
        if b.kind == "plain":
            out += [f"    public const int {b.name}{f.name} = {b.offset + f.offset};" for f in b.fields]
        if b.kind == "ring":
            out += [f"    public const int {b.name}Slots = {b.slots};", f"    public const int {b.name}Slot = {b.record.size};",
                    f"    public const int {b.name}First = {b.offset + b.slots_at};"]
    out += ["}"]
    for e in enums.values():
        out += [""] + doc(e.doc) + [f"public enum {n(e.name)} : {TYPES[e.type]}", "{"]
        for v in e.values:
            out += [f"    /// <summary>{v['doc'].replace('&', 'and')}</summary>", f"    {v['name']} = {v['value']},"]
        out += ["}"]
    for g in flags.values():
        out += [""] + doc(g["doc"]) + [f"public static class {n(g['name'])}", "{"]
        for v in g["values"]:
            out += [f"    /// <summary>{v['doc'].replace('&', 'and')}</summary>", f"    public const {TYPES[g['type']]} {v['name']} = {v['value']};"]
        out += ["}"]
    for r in records.values():
        out += [""] + doc(r.doc) + [f"public struct {n(r.name)}", "{"] + [member(f, n) for f in r.fields] + \
            ([f"    public {n(r.name)}() {{ }}"] if any(f.type == "bytes" for f in r.fields) else []) + ["}"]
    for b in blocks:
        if b.kind == "seqlock":
            out += [""] + doc(b.doc) + [f"public sealed class {n(b.name)}", "{"] + [member(f, n) for f in b.fields] + ["}"]
    out += ["", "/// <summary>A ring's event: read, not written yet (or being written), or overwritten by a newer one.</summary>",
            f"public enum {n('Read')}", "{", "    Ok,", "    NotYet,", "    Lost,", "}", ""]
    out += view(blocks, records, n, c["class"])
    return "\n".join(out) + "\n"


def view(blocks, records, n, layout):
    out = doc("The board's memory (a mapping's first byte, aligned to 8 at least): every word read and written as one "
              "volatile access, a seqlock block as one group. Holds no state of its own.")
    out += [f"public readonly unsafe struct {n('View')}", "{", "    private readonly byte* _at;", "",
            f"    public {n('View')}(byte* at) => _at = at;", "",
            "    /// <summary>The launcher's side of the header, on a board of zeros: made for this version. The magic goes last.</summary>",
            "    public void Make(uint launcherPid)", "    {", f"        HeaderSize = {layout}.Size;", f"        HeaderVersion = {layout}.Version;",
            "        HeaderLauncherPid = launcherPid;", f"        HeaderMagic = {layout}.Magic;", "    }", "",
            "    /// <summary>Whether the game has taken the board: null not yet; true taken, of this version; false refused (another",
            "    /// version, or too small a board): the game then writes nothing more, and the launcher goes without.</summary>",
            "    public bool? Taken => HeaderRunnerVersion == 0 ? null :",
            f"        HeaderRunnerVersion == {layout}.Version && HeaderRunnerSize == {layout}.Size && HeaderSize >= {layout}.Size;"]
    for b in blocks:
        out.append("")
        if b.kind == "plain":
            for f in b.fields:
                t = value_type(f, n)
                get = load(f, f"{layout}.{b.name}{f.name}", "v", n)[0].removeprefix("v = ").rstrip(";")
                put = store(f, f"{layout}.{b.name}{f.name}", "value", n)[0].rstrip(";")
                out += [f"    /// <summary>{b.name} ({b.writer} writes).</summary>",
                        f"    public {t} {b.name}{f.name}", "    {", f"        get => {get};", f"        set => {put};", "    }"]
        elif b.kind == "seqlock":
            t, base = n(b.name), f"{layout}.{b.name}"
            out += [f"    /// <summary>{b.name} ({b.writer} writes), as one group. Its writer alone calls this.</summary>",
                    f"    public void Write{b.name}({t} v)", "    {", f"        ref var seq = ref *(uint*)(_at + {base});",
                    "        var s = Volatile.Read(ref seq) & ~1u;", "        Volatile.Write(ref seq, s + 1);",
                    "        Interlocked.MemoryBarrier();"]
            for f in b.fields:
                out += indent(store(f, f"{base} + {f.offset}", f"v.{f.name}", n), "        ")
            out += ["        Volatile.Write(ref seq, s + 2);", "    }", "",
                    f"    /// <summary>Reads {b.name} into <paramref name=\"into\"/>; false when every try met the writer at work "
                    "(then <paramref name=\"into\"/> holds nothing to use).</summary>",
                    f"    public bool TryRead{b.name}({t} into, int tries = 64)", "    {",
                    f"        ref var seq = ref *(uint*)(_at + {base});", "        for (var t = 0; t < tries; t++)", "        {",
                    "            var s = Volatile.Read(ref seq);", "            if ((s & 1) != 0)", "            {",
                    "                Thread.SpinWait(4);", "                continue;", "            }"]
            for f in b.fields:
                out += indent(load(f, f"{base} + {f.offset}", f"into.{f.name}", n), "            ")
            out += ["            Interlocked.MemoryBarrier();", "            if (Volatile.Read(ref seq) == s)", "            {",
                    "                return true;", "            }", "        }", "        return false;", "    }"]
        else:
            r, name, rt = b.record, b.name, n(b.record.name)
            slot = f"{layout}.{name}First + (int)(number % {layout}.{name}Slots) * {layout}.{name}Slot"
            out += [f"    /// <summary>{name}: how many events were written.</summary>",
                    f"    public ulong {name}Head => Volatile.Read(ref *(ulong*)(_at + {layout}.{name}));", "",
                    f"    /// <summary>Writes event <paramref name=\"number\"/> (the writer's to hand out) into its slot.</summary>",
                    f"    public void Write{name}(ulong number, in {rt} v)", "    {", f"        var base_ = {slot};",
                    "        ref var seq = ref *(uint*)(_at + base_);", "        var word = (uint)(number * 2 + 2);",
                    "        Volatile.Write(ref seq, word - 1);", "        Interlocked.MemoryBarrier();"]
            for f in r.fields[1:]:
                out += indent(store(f, f"base_ + {f.offset}", f"v.{f.name}", n), "        ")
            out += ["        Volatile.Write(ref seq, word);", f"        ref var head = ref *(ulong*)(_at + {layout}.{name});",
                    "        var h = Volatile.Read(ref head);",
                    "        while (h < number + 1)", "        {", "            var was = Interlocked.CompareExchange(ref head, number + 1, h);",
                    "            if (was == h)", "            {", "                break;", "            }", "            h = was;", "        }", "    }", "",
                    f"    /// <summary>Reads event <paramref name=\"number\"/>.</summary>",
                    f"    public {n('Read')} Read{name}(ulong number, out {rt} v, int tries = 64)", "    {",
                    f"        var base_ = {slot};", "        ref var seq = ref *(uint*)(_at + base_);", "        var word = (uint)(number * 2 + 2);",
                    "        v = default;", "        for (var t = 0; t < tries; t++)", "        {", "            var s = Volatile.Read(ref seq);",
                    "            var ahead = (int)(s - word);", "            if (ahead > 0)", "            {",
                    f"                return {n('Read')}.Lost;", "            }", "            if (ahead < -1)", "            {",
                    f"                return {n('Read')}.NotYet;", "            }", "            if (ahead == -1)", "            {",
                    "                Thread.SpinWait(4);", "                continue;", "            }", "            v.Seq = s;"]
            for f in r.fields[1:]:
                out += indent(load(f, f"base_ + {f.offset}", f"v.{f.name}", n), "            ")
            out += ["            Interlocked.MemoryBarrier();", "            if (Volatile.Read(ref seq) == s)", "            {",
                    f"                return {n('Read')}.Ok;", "            }", "        }", f"        return {n('Read')}.NotYet;", "    }"]
    for r in records.values():
        rt = n(r.name)
        out += ["", f"    private void Load{r.name}(int at, ref {rt} v)", "    {"]
        for f in r.fields:
            out += indent(load(f, f"at + {f.offset}", f"v.{f.name}", n), "        ")
        out += ["    }", "", f"    private void Store{r.name}(int at, in {rt} v)", "    {"]
        for f in r.fields:
            out += indent(store(f, f"at + {f.offset}", f"v.{f.name}", n), "        ")
        out += ["    }"]
    return out + ["}"]
