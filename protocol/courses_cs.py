"""The courses' names as C# (generated/CourseTable.g.cs): Online.Protocol's CourseTable, which CourseNames reads (the
launcher's, the server's status page's and the vote's names of a course)."""

GENERATED = "// <auto-generated>Generated by protocol/generate.py from protocol/courses.toml. Do not edit.</auto-generated>"


def text(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(t):
    out = [GENERATED, "namespace Online.Protocol;", "",
           "/// <summary>The courses' names, as players know them (protocol/courses.toml; the game writes the story's names",
           "/// from the same file): the cup courses by the game's course number, and the story's chapters that have a name",
           "/// of their own. CourseNames puts them together.</summary>",
           "public static class CourseTable",
           "{",
           "    /// <summary>The story's first stage: the game's course number of chapter 1, the chapters numbered on from it.</summary>",
           f"    public const int FirstStoryStage = {t['first']};", "",
           "    /// <summary>The story's chapters, as the game numbers them.</summary>",
           f"    public const int StoryChapters = {t['chapters']};", "",
           "    /// <summary>The longest name, in characters.</summary>",
           f"    public const int Longest = {t['longest']};", "",
           "    /// <summary>The cup courses: the game's course number, the venue, the course's own name.</summary>",
           "    public static readonly IReadOnlyList<(int Course, string Place, string Track)> Courses =",
           "    ["]
    out += [f"        ({c}, {text(p)}, {text(tr)})," for c, p, tr in t["courses"]]
    out += ["    ];", "",
            "    /// <summary>The story's chapters with a name of their own: the chapter, its stage's course number, the name.</summary>",
            "    public static readonly IReadOnlyList<(int Chapter, int Course, string Track)> StoryChapterNames =",
            "    ["]
    out += [f"        ({ch}, {c}, {text(tr)})," for ch, c, tr in t["chapters_named"]]
    out += ["    ];", "}", ""]
    return "\n".join(out)
