"""The host's rules' C++ header generate.py writes (the game's core: port/core/src/files_match.cpp): the race block's
words of the rules the games apply, their ranges, and IntoRace, which takes a match start's "rules" into those
words as the game applies them. IntoRace is a template over the reader of the rules object (Number(key, absent) and
Flag(key), port/core/src/files_match.cpp), so this header needs nothing of the core. Header-only, standard library
only, C++20."""

from board_cxx import comment

GENERATED = "// Generated by protocol/generate.py from protocol/rules.toml. Do not edit."


def text(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def upper(r):
    return r.name.replace("-", "_").upper()


def word(r, steps):
    if r.kind == "switch":
        return f"rules.Flag({text(r.race.key)}) ? 1u : 0u"
    taken = (f"static_cast<std::uint32_t>(std::clamp(rules.Number({text(r.race.key)}, {float(r.race.absent)!r}), "
             f"{float(r.race.low)!r}, {float(r.race.high)!r}))")
    if r.race.steps == "seconds":
        return f"{taken} * {steps}u"
    if r.race.steps == "ms":
        return f"{taken} * {steps}u / {r.race.per_second}u"
    return taken


def emit(s):
    ns = s["codec"]["cxx"]["namespace"]
    steps = s["block"]["steps_a_second"]
    out = [GENERATED, "// A host's rules the games apply (protocol/rules.toml): the race block's words and how a match start's",
           "// \"rules\" become them.", "// SPDX-License-Identifier: GPL-3.0-or-later", "", "#pragma once", "",
           "#include <algorithm>", "#include <array>", "#include <cstdint>", "", f"namespace {ns}", "{",
           f"inline constexpr std::uint32_t RACE_SIZE = {s['block']['size']}u;",
           f"inline constexpr std::uint32_t STEPS_A_SECOND = {steps}u;"]
    for r in s["race"]:
        out.append("")
        out += comment(f"{r.name} (\"{r.race.key}\"): {r.race.doc}.")
        out.append(f"inline constexpr std::uint32_t {r.race.word} = {r.race.at}u;")
        out.append(f"inline constexpr std::uint32_t {upper(r)}_LEAST = {r.least}u, {upper(r)}_MOST = {r.most}u, "
                   f"{upper(r)}_STEP = {r.step}u;")
    out += ["", "// A rule's word: its name, its member of a match start's rules, its offset in the race block.",
            "struct Word", "{", "  const char* name;", "  const char* key;", "  std::uint32_t at;", "};",
            f"inline constexpr std::array<Word, {len(s['race'])}> WORDS = {{{{"]
    out += [f"    {{{text(r.name)}, {text(r.race.key)}, {r.race.word}}}," for r in s["race"]]
    out += ["}};", ""]
    out += comment("The rules (a match start's \"rules\"; R gives Number(key, absent), the member's number or "
                   "`absent` when it has none, and Flag(key), true only for a member that is true) into the race "
                   "block's words, big-endian: a number brought into its range (a delay from 0, off), as whole steps "
                   "of the race where it counts time. A rule a match start leaves out is the game's own way.")
    out += ["template <typename R>", "void IntoRace(const R& rules, unsigned char* block)", "{",
            "  const auto put = [block](std::uint32_t at, std::uint32_t v) {",
            "    block[at] = static_cast<unsigned char>(v >> 24);",
            "    block[at + 1] = static_cast<unsigned char>(v >> 16);",
            "    block[at + 2] = static_cast<unsigned char>(v >> 8);",
            "    block[at + 3] = static_cast<unsigned char>(v);", "  };"]
    out += [f"  put({r.race.word}, {word(r, steps)});" for r in s["race"]]
    out += ["}", f"}}  // namespace {ns}", ""]
    return "\n".join(out)
