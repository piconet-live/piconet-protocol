"""The host's rules' C++ header generate.py writes (the game's core: port/core/src/files_match.cpp): the race block's
words of the rules the games apply, their ranges, and IntoRace, which takes a match start's "rules" into those
words as the game applies them. IntoRace is a template over the reader of the rules object (Number(key, absent) and
Flag(key), port/core/src/files_match.cpp), so this header needs nothing of the core. Header-only, standard library
only, C++20."""

from board_cxx import comment

GENERATED = "// Generated by protocol/generate.py from protocol/rules.toml. Do not edit."


def text(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def upper(r):
    return r.name.replace("-", "_").upper()


def word(r, steps):
    if r.kind == "switch":
        return f"rules.Flag({text(r.race.key)}) ? 1u : 0u"
    taken = (f"static_cast<std::uint32_t>(std::clamp(rules.Number({text(r.race.key)}, {float(r.race.absent)!r}), "
             f"{float(r.race.low)!r}, {float(r.race.high)!r}))")
    if r.race.steps == "seconds":
        return f"{taken} * {steps}u"
    if r.race.steps == "ms":
        return f"{taken} * {steps}u / {r.race.per_second}u"
    return taken


def emit(s):
    ns = s["codec"]["cxx"]["namespace"]
    steps = s["block"]["steps_a_second"]
    out = [GENERATED, "// A host's rules the games apply (protocol/rules.toml): the race block's words and how a match start's",
           "// \"rules\" become them.", "// SPDX-License-Identifier: GPL-3.0-or-later", "", "#pragma once", "",
           "#include <algorithm>", "#include <array>", "#include <cstdint>", "", f"namespace {ns}", "{",
           f"inline constexpr std::uint32_t RACE_SIZE = {s['block']['size']}u;",
           f"inline constexpr std::uint32_t STEPS_A_SECOND = {steps}u;"]
    for r in s["race"]:
        out.append("")
        out += comment(f"{r.name} (\"{r.race.key}\"): {r.race.doc}.")
        out.append(f"inline constexpr std::uint32_t {r.race.word} = {r.race.at}u;")
        out.append(f"inline constexpr std::uint32_t {upper(r)}_LEAST = {r.least}u, {upper(r)}_MOST = {r.most}u, "
                   f"{upper(r)}_STEP = {r.step}u;")
    out += ["", "// A rule's word: its name, its member of a match start's rules, its offset in the race block.",
            "struct Word", "{", "  const char* name;", "  const char* key;", "  std::uint32_t at;", "};",
            f"inline constexpr std::array<Word, {len(s['race'])}> WORDS = {{{{"]
    out += [f"    {{{text(r.name)}, {text(r.race.key)}, {r.race.word}}}," for r in s["race"]]
    out += ["}};", ""]
    out += comment("The rules (a match start's \"rules\"; R gives Number(key, absent), the member's number or "
                   "`absent` when it has none, and Flag(key), true only for a member that is true) into the race "
                   "block's words, big-endian: a number brought into its range (a delay from 0, off), as whole steps "
                   "of the race where it counts time. A rule a match start leaves out is the game's own way.")
    out += ["template <typename R>", "void IntoRace(const R& rules, unsigned char* block)", "{",
            "  const auto put = [block](std::uint32_t at, std::uint32_t v) {",
            "    block[at] = static_cast<unsigned char>(v >> 24);",
            "    block[at + 1] = static_cast<unsigned char>(v >> 16);",
            "    block[at + 2] = static_cast<unsigned char>(v >> 8);",
            "    block[at + 3] = static_cast<unsigned char>(v);", "  };"]
    out += [f"  put({r.race.word}, {word(r, steps)});" for r in s["race"]]
    out += ["}", f"}}  // namespace {ns}", ""]
    return "\n".join(out)


# ---- the host's rules whole, for a C++ reader of a lobby's rules (the native program's link: its custom lobbies'
# rules panel and their words, port/native/net/custom_rules.cpp): HostRules.All and Restore as Online.Protocol's
# HostRules.g.cs holds them, each its name, label, reach, kind, range, Quick Play's value, unit, refusal's words,
# server option and setup word. A range or default named by a C# constant ("GameFacts.Limits.Seats") is its number:
# GameFacts.g.cs's Limits (this folder's generated file, port/facts' numbers) and ServerRules.QuickPlayLatencyLimitMs
# (messages.toml's ServerRules.latencyLimitMs default, the codec's). Header-only, C++17, standard library only.

HOST_GENERATED = "// Generated by protocol/generate.py from protocol/rules.toml. Do not edit."
REACHES_CXX = {"alone": "Alone", "together": "Together", "server": "Server", "practice": "Practice"}
KINDS_CXX = {"course": "Course", "courses": "Courses", "number": "Number", "switch": "Switch", "range": "Range",
             "choice": "Choice", "delay": "Delay", "machines": "Machines", "pack": "Pack", "text": "Text"}


def constants(game_facts, quick_play_latency):
    """The C# constants rules.toml names, as numbers: GameFacts.Limits' members (GameFacts.g.cs's `public const int`
    lines inside `class Limits`) and ServerRules.QuickPlayLatencyLimitMs."""
    import re
    out, inside = {}, False
    for line in game_facts.splitlines():
        if re.match(r"\s*public static (partial )?class Limits\b", line):
            inside = True
        elif inside and re.match(r"\s*public static (partial )?class ", line):
            break
        elif inside and (m := re.match(r"\s*public const (?:int|uint) (\w+) = (-?\d+);", line)):
            out["GameFacts.Limits." + m.group(1)] = int(m.group(2))
    out["ServerRules.QuickPlayLatencyLimitMs"] = quick_play_latency
    return out


def emit_host(s, named):
    def number(v, what, r):
        if type(v) is int:
            return v
        if v not in named:
            raise ValueError(f"rule {r.name}: {what} {v} is no constant the C++ header knows")
        return named[v]
    ns = "fzgx::host_rules"
    out = [HOST_GENERATED,
           "// A host's rules whole (protocol/rules.toml), as Online.Protocol's HostRules holds them: each rule's name, the",
           "// label a player's panel shows, whom it concerns, what it is, its range and Quick Play's value.",
           "// SPDX-License-Identifier: GPL-3.0-or-later", "", "#pragma once", "", "#include <array>", "#include <cstdint>",
           "#include <string_view>", "", f"namespace {ns}", "{",
           "// Online.Protocol RuleReach and RuleKind, in their order",
           "enum class Reach : std::uint8_t", "{", "  " + ", ".join(REACHES_CXX.values()), "};",
           "enum class Kind : std::uint8_t", "{", "  " + ", ".join(KINDS_CXX.values()), "};", "",
           "// One rule (Online.Protocol HostRule): unit \"s\", \"ms\" or \"\"; taken \"\" for none (the C#'s null); flag the",
           "// server's option (\"\" none); setupWord the game mode's word that sets it (\"\" none).",
           "struct Rule", "{", "  std::string_view name, label;", "  Reach reach;", "  Kind kind;",
           "  int least, most, step, default_;", "  std::string_view unit, taken, flag, setupWord;", "",
           "  // HostRule.Takes: inside the range on its steps; a delay's 0 (off) too",
           "  constexpr bool Takes(int v) const",
           "  {",
           "    return (kind == Kind::Delay && v == 0) || (v >= least && v <= most && (v - least) % step == 0);",
           "  }",
           "  // HostRule.Kept: the nearest number the rule takes (a delay below its least: off)",
           "  constexpr int Kept(int v) const",
           "  {",
           "    if (kind == Kind::Delay && v < least)",
           "      return 0;",
           "    const int inside = v < least ? least : v > most ? most : v;",
           "    const int k = least + (inside - least + step / 2) / step * step;",
           "    return k < most ? k : most;",
           "  }",
           "};", ""]
    every = [r for r in s["rules"]]
    for r in every:
        least, most, step, default = (number(r.least, "least", r), number(r.most, "most", r),
                                      number(r.step, "step", r), number(r.default, "default", r))
        flag = r.race.flag if r.race and r.race.flag else ""
        setup = r.setup if r.setup not in ("flow", "practice") else ""
        ident = r.name.replace("-", "_").upper()
        out.append(f"inline constexpr Rule {ident}{{{text(r.name)}, {text(r.label)}, Reach::{REACHES_CXX[r.reach]}, "
                   f"Kind::{KINDS_CXX[r.kind]}, {least}, {most}, {step}, {default}, {text(r.unit)}, "
                   f"{text(r.taken or '')}, {text(flag)}, {text(setup)}}};")
    listed = [r for r in every if r.reach != "practice"]
    out += ["", "// HostRules.All: every rule but a practice's alone, in the operator's order",
            f"inline constexpr std::array<const Rule*, {len(listed)}> ALL = {{{{"]
    out += [f"    &{r.name.replace('-', '_').upper()}," for r in listed]
    out += ["}};", "", "// HostRules.Named: a rule by its name (a practice's too); nullptr: no such rule",
            "constexpr const Rule* Named(std::string_view name)", "{"]
    out += [f"  if (name == {r.name.replace('-', '_').upper()}.name)\n    return &{r.name.replace('-', '_').upper()};"
            for r in every]
    out += ["  return nullptr;", "}", f"}}  // namespace {ns}", ""]
    return "\n".join(out)
