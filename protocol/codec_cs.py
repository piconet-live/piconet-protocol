"""The C# codec generate.py writes, which Online.Protocol compiles: RelayProtocol, PacketType, a record per packet and
the flag constants, the API the hand-written RelayPackets.cs it replaced had, so no caller changed."""

TYPES = {"u8": "byte", "u32": "uint", "u64": "ulong", "i64": "long", "records": "byte[]"}
READS = {"u32": "BinaryPrimitives.ReadUInt32BigEndian", "u64": "BinaryPrimitives.ReadUInt64BigEndian",
         "i64": "BinaryPrimitives.ReadInt64BigEndian"}
WRITES = {"u32": "BinaryPrimitives.WriteUInt32BigEndian", "u64": "BinaryPrimitives.WriteUInt64BigEndian",
          "i64": "BinaryPrimitives.WriteInt64BigEndian"}


def pascal(key):
    return "".join(part.capitalize() for part in key.split("_"))


def escape(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def summary(text, indent=""):
    return [f"{indent}/// <summary>{escape(text)}</summary>"]


def type_of(f):
    kind = f.cs or TYPES[f.type]
    return f"{kind}?" if f.optional else kind


def mark_test(protocol, data):
    return " || ".join(f"{data}[{i}] != (byte)'{c}'" for i, c in enumerate(protocol["mark"]))


def mark_equal(protocol, data):
    return " && ".join(f"{data}[{i}] == (byte)'{c}'" for i, c in enumerate(protocol["mark"]))


def head(protocol):
    mark = protocol["mark"]
    drives = ", ".join(f"0x{b:02X}" if b else "0" for b in protocol["ai_drives"])
    return ["// <auto-generated>Generated by protocol/generate.py from protocol/relay.toml. Do not edit.</auto-generated>",
            "#nullable enable", "", "using System.Buffers.Binary;", "", f"namespace {protocol['codec']['csharp']['namespace']};", "",
            f"/// <summary>The game-relay protocol (protocol/relay.toml): small big-endian UDP packets. Header: the mark",
            f"/// '{mark}', the version, the type.</summary>",
            f"public static class {protocol['codec']['csharp']['class']}", "{",
            f"    public const byte Version = {protocol['version']};",
            f"    public const int RecordSize = {protocol['record_size']};",
            f"    public const int HeaderSize = {protocol['header_size']};", "",
            "    /// <summary>The \"AI drives\" record: the game's AI keeps the seat whose official input it is.</summary>",
            f"    public static ReadOnlySpan<byte> AiDrives => [{drives}];", "",
            "    /// <summary>At most this many frames in one packet (inputs or official frames).</summary>",
            f"    public const int MaxFramesPerPacket = {protocol['max_frames_per_packet']};", "",
            "    /// <summary>The records an official packet carries stay within this many bytes.</summary>",
            f"    public const int MaxPayload = {protocol['max_payload']};", "",
            "    /// <summary>Bytes of the seat's key that open every packet the relay sends a game (RelayKeys).</summary>",
            f"    public const int KeySize = {protocol['key_size']};", ""]


def dispatch(protocol, packets):
    out = ["    public static byte[] Encode(RelayPacket packet) => packet switch", "    {"]
    out += [f"        {p.record} p => Encode{p.name}(p)," for p in packets]
    out += ['        _ => throw new ArgumentException($"unknown packet {packet.GetType().Name}", nameof(packet)),',
            "    };", "",
            "    /// <summary>The packet with the seat's key it goes out with (a packet the relay sends a game; any other "
            "packet", "    /// as it is).</summary>",
            "    public static RelayPacket WithKey(RelayPacket packet, ulong key) => packet switch", "    {"]
    out += [f"        {p.record} p => p with {{ Key = key }}," for p in packets if p.from_relay]
    out += ["        _ => packet,", "    };", "",
            "    /// <summary>A packet the relay sends a game: its body opens with the seat's key.</summary>",
            "    public static bool FromRelay(PacketType type) =>",
            "        type is " + "\n            or ".join(f"PacketType.{p.name}" for p in packets if p.from_relay) + ";", "",
            "    /// <summary>The relay protocol version of a packet from another version of the game or relay (null: "
            "this version,", "    /// or not a relay packet).</summary>",
            "    public static byte? ForeignVersion(ReadOnlySpan<byte> data) =>",
            f"        data.Length >= HeaderSize && {mark_equal(protocol, 'data')} && data[{len(protocol['mark'])}] "
            f"!= Version ? data[{len(protocol['mark'])}] : null;", "",
            "    /// <summary>Decodes a packet; null for anything malformed or foreign.</summary>",
            "    public static RelayPacket? Decode(ReadOnlySpan<byte> data)", "    {",
            f"        if (data.Length < HeaderSize || {mark_test(protocol, 'data')} || data[{len(protocol['mark'])}] "
            "!= Version)", "        {", "            return null;", "        }",
            "        var b = data[HeaderSize..];",
            f"        return (PacketType)data[{len(protocol['mark']) + 1}] switch", "        {"]
    out += [f"            PacketType.{p.name} => Decode{p.name}(b)," for p in packets]
    out += ["            _ => null,", "        };", "    }", "",
            "    /// <summary>The number of seats set in a player-seat mask.</summary>",
            "    public static int SeatCount(uint mask) => System.Numerics.BitOperations.PopCount(mask);", "",
            "    private static byte[] Start(PacketType type, int body)", "    {",
            "        var a = new byte[HeaderSize + body];"]
    out += [f"        a[{i}] = (byte)'{c}';" for i, c in enumerate(protocol["mark"])]
    n = len(protocol["mark"])
    out += [f"        a[{n}] = Version;", f"        a[{n + 1}] = (byte)type;", "        return a;", "    }"]
    return out


def write(f, value):
    if f.type == "u8":
        return f"b[{f.offset}] = (byte){value};" if f.cs else f"b[{f.offset}] = {value};"
    return f"{WRITES[f.type]}(b[{f.offset}..], {value});"


def read(f):
    return f"b[{f.offset}]" if f.type == "u8" else f"{READS[f.type]}(b[{f.offset}..])"


def encoder(p):
    body = str(p.head)
    if p.optional:
        body += f" + (p.{p.optional.name} is null ? 0 : {p.optional.size})"
    if p.records:
        body += f" + p.{p.records.name}.Length"
    out = ["", f"    private static byte[] Encode{p.name}({p.record} p)", "    {",
           f"        var a = Start(PacketType.{p.name}, {body});", "        var b = a.AsSpan(HeaderSize);"]
    for f in p.fixed:
        if f.optional:
            out.append(f"        if (p.{f.name} is {{ }} {f.name[0].lower() + f.name[1:]})")
            out += ["        {", f"            {write(f, f.name[0].lower() + f.name[1:])}", "        }"]
        else:
            out.append(f"        {write(f, 'p.' + f.name)}")
    if p.records:
        out.append(f"        p.{p.records.name}.CopyTo(b[{p.head}..]);")
    return out + ["        return a;", "    }"]


def decoder(p):
    sig = f"    private static {p.record}? Decode{p.name}(ReadOnlySpan<byte> b)"
    args = {f.name: read(f) for f in p.fixed}

    def made():
        return f"new {p.record}({', '.join(args[f.name] for f in p.cs_fields)})"
    if p.optional:
        whole = p.head + p.optional.size
        args[p.optional.name] = f"b.Length == {whole} ? {read(p.optional)} : null"
        return ["", sig + " =>", f"        b.Length == {p.head} || b.Length == {whole} ? {made()} : null;"]
    if not p.records:
        return ["", sig + " =>", f"        b.Length == {p.head} ? {made()} : null;"]
    r = p.records
    per = f" * SeatCount({read(r.seats)})" if r.seats else ""
    args[r.count.name] = "count" if r.count.cs else "(byte)count"
    args[r.name] = f"b[{p.head}..].ToArray()"
    return ["", sig, "    {", f"        if (b.Length < {p.head})", "        {", "            return null;", "        }",
            f"        int count = {read(r.count)};",
            f"        return b.Length == {p.head} + (count{per} * RecordSize) ? {made()} : null;", "    }"]


def parameter(f):
    default = " = null" if f.optional else (f" = {f.default}" if f.default is not None else "")
    return f"{type_of(f)} {f.name}{default}"


def flags(protocol):
    out = []
    for group in protocol["flags"]:
        out += [""] + summary(group.get("doc", "")) + [f"public static class {group['name']}", "{"]
        for v in group["values"]:
            out += summary(v.get("doc", ""), "    ") + [f"    public const {TYPES[group['type']]} {v['name']} = {v['value']};", ""]
        out[-1:] = ["}"]
    return out


def records(packets):
    out = ["}", "", "public enum PacketType : byte", "{"]
    out += [f"    {p.name} = {p.type}," for p in packets]
    out += ["}", "", "public abstract record RelayPacket(PacketType Type);"]
    for p in packets:
        params = [parameter(f) for f in p.cs_fields]
        out += [""] + summary(p.doc)
        out.append(f"public sealed record {p.record}({', '.join(params)}) : RelayPacket(PacketType.{p.name});")
    return out


def emit(protocol, packets):
    out = head(protocol) + dispatch(protocol, packets)
    for p in packets:
        out += encoder(p) + decoder(p)
    return "\n".join(out + records(packets) + flags(protocol)) + "\n"
