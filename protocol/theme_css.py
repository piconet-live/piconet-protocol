"""The site's and the service's custom properties (generated/theme.g.css) from the look's tokens (theme.py): one
:root block, each token under its name (--on-accent): the colours by one name each (theme.opaque_colours), a tint as
rgba, a size in px (a number as it is), a duration in ms, the easing as cubic-bezier, a shadow."""

import theme

HEAD = "/* Generated by protocol/generate.py from protocol/theme.tokens.json. Do not edit. */\n"


def rgba(hex_colour, alpha):
    r, g, b = (int(hex_colour[i:i + 2], 16) for i in (1, 3, 5))
    return f"rgba({r}, {g}, {b}, {f'{alpha:.3f}'.rstrip('0').rstrip('.')})"


def emit(tokens):

    out = [HEAD, ":root {\n"]
    for name, t in theme.opaque_colours(tokens).items():
        out.append(f"  --{name}: {t.colour};\n")
    for t in tokens:
        if t.group == "brush" and t.opacity != 1.0:
            out.append(f"  --{t.name}: {rgba(t.colour, t.opacity)};\n")
        elif t.group == "size":
            out.append(f"  --{t.name}: {t.number!r}{'px' if t.type == 'dimension' else ''};\n")
        elif t.group == "duration":
            out.append(f"  --{t.name}: {t.ms}ms;\n")
        elif t.group == "easing":
            out.append(f"  --{t.name}: cubic-bezier({', '.join(f'{v:g}' for v in t.curve)});\n")
        elif t.group == "shadow":
            s = t.shadow
            alpha = int(s["color"][7:9], 16) / 255
            out.append(f"  --{t.name}: {s['offsetX']}px {s['offsetY']}px {s['blur']}px {s['spread']}px {rgba(s['color'][:7], alpha)};\n")
    out.append("}\n")
    return "".join(out)
