"""The game mode system's vocabulary and bytecode as C# (generated/ModeWords.g.cs): Online.Protocol's ModeWords, which
the compiler (net/src/Online.Protocol/Modes) reads: the api's limits, the operations and every word by name."""

GENERATED = "// <auto-generated>Generated by protocol/generate.py from protocol/modes.toml. Do not edit.</auto-generated>"


def text(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def xml(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def cs_type(t):
    return {"int": "ModeType.Int", "real": "ModeType.Real", "bool": "ModeType.Bool", "switch": "ModeType.Bool", "seat": "ModeType.Seat",
            "seats": "ModeType.Seats", "vec": "ModeType.Vec"}[t]


def number(v, t):
    return f"{float(v)!r}f" if t == "real" else str(int(v))


def emit(t):
    api = t["api"]
    out = [GENERATED, f"namespace {t['namespace_cs']};", "",
           "/// <summary>The bytecode's operations (protocol/modes.toml; formats.md section 9).</summary>",
           "public enum ModeOp : byte", "{"]
    out += [f"    /// <summary>{xml(o['doc'])}</summary>\n    {o['name']} = {o['code']:#04x}," if o["doc"] else
            f"    {o['name']} = {o['code']:#04x}," for o in t["ops"]]
    out += ["}", ""]
    for kind, name, what in (("events", "ModeEvent", "A rule's event"), ("setups", "ModeSetup", "A setup word"),
                             ("seat_reads", "ModeSeatRead", "A read of a seat"),
                             ("race_reads", "ModeRaceRead", "A read of the race"), ("actions", "ModeAction", "An action")):
        out += [f"/// <summary>{what} (protocol/modes.toml).</summary>", f"public enum {name} : byte", "{"]
        out += [f"    /// <summary><c>{e['name']}</c></summary>\n    {e['pascal']} = {e['id']}," for e in t[kind]]
        out += ["}", ""]
    out += ["/// <summary>The vocabulary of one api, by the names a mode file writes (protocol/modes.toml).</summary>",
            "public static partial class ModeWords", "{",
            f"    /// <summary>The newest rule set this build compiles and runs: what a package carries as its api.</summary>\n    public const int Api = {api['number']};",
            f"    /// <summary>The newest game version this build knows: a mode file names one (<c>api {t['levels']['newest']};</c>).</summary>\n"
            f"    public const string ApiVersion = {text(t['levels']['newest'])};",
            "    /// <summary>The rule sets, oldest first: its number and the game version it arrived in. A version between two\n"
            "    /// has the earlier one's.</summary>",
            "    public static readonly IReadOnlyList<(int Number, string Version)> RuleSets =",
            "        [" + ", ".join(f"({r['number']}, {text(r['version'])})" for r in t["levels"]["rule_sets"]) + "];"]
    out += [f"    /// <summary>The api's limit <c>{k}</c>.</summary>\n    public const int "
            + "".join(p.title() for p in k.split("_")) + f" = {v};" for k, v in api.items() if k != "number"]
    out += ["", "    /// <summary>An operation's size in bytes, operands included.</summary>",
            "    public static int Size(ModeOp op) => op switch", "    {"]
    out += [f"        ModeOp.{o['name']} => {o['size']}," for o in t["ops"]]
    out += ["        _ => 0,", "    };", "",
            "    /// <summary>The events: name, id, continuous, whether it binds a seat, and the type of the second name it",
            "    /// binds (null: none; <c>ko(v, by)</c> a seat, <c>out(s, cause)</c> an int).</summary>",
            "    public static readonly IReadOnlyList<(string Name, ModeEvent Id, bool Continuous, bool BindsSeat, ModeType? Second)> Events =",
            "    ["]
    second = {"seat seat": "ModeType.Seat", "seat int": "ModeType.Int"}
    out += [f"        ({text(e['name'])}, ModeEvent.{e['pascal']}, {'true' if e['kind'] == 'continuous' else 'false'}, "
            f"{'true' if 'binds' in e else 'false'}, {second.get(e.get('binds', ''), 'null')})," for e in t["events"]]
    out += ["    ];", "",
            "    /// <summary>The setup words: name, id, arguments (name, type, least, most, default, what on is, what always is); Lobby: the coordinator's "
            "alone, not in the package; Form: how the file writes it (range, text, list; empty: its arguments).</summary>",
            "    public static readonly IReadOnlyList<(string Name, ModeSetup Id, IReadOnlyList<ModeArgument> Args, bool Lobby, string Form)> Setups =",
            "    ["]
    for s in t["setups"]:
        args = ", ".join(
            f"new ModeArgument({text(a.get('name', ''))}, {cs_type(a['type'])}, {number(a.get('least', 0), a['type'])}, "
            f"{a.get('always', 1) if a['type'] == 'switch' else number(a.get('most', 0), a['type'])}, {number(a['default'], a['type']) if 'default' in a else 'null'}"
            + (f", {a['on']})" if "on" in a else f", Always: {a['always']})" if "always" in a else ")")
            for a in s.get("args", []))
        out.append(f"        ({text(s['name'])}, ModeSetup.{s['pascal']}, [{args}], {'true' if s.get('lobby') else 'false'}, {text(s.get('form', ''))}),")
    out += ["    ];", "",
            "    /// <summary>The reads of a seat (<c>seat.NAME</c>): name, id, type.</summary>",
            "    public static readonly IReadOnlyList<(string Name, ModeSeatRead Id, ModeType Type)> SeatReads =",
            "    ["]
    out += [f"        ({text(r['name'])}, ModeSeatRead.{r['pascal']}, {cs_type(r['type'])})," for r in t["seat_reads"]]
    out += ["    ];", "",
            "    /// <summary>The reads of the race (<c>race.NAME</c>): name, id, type.</summary>",
            "    public static readonly IReadOnlyList<(string Name, ModeRaceRead Id, ModeType Type)> RaceReads =",
            "    ["]
    out += [f"        ({text(r['name'])}, ModeRaceRead.{r['pascal']}, {cs_type(r['type'])})," for r in t["race_reads"]]
    out += ["    ];", "",
            "    /// <summary>The actions: name, id, the types of their arguments in order.</summary>",
            "    public static readonly IReadOnlyList<(string Name, ModeAction Id, IReadOnlyList<ModeType> Args)> Actions =",
            "    ["]
    choices = {c["name"]: c for c in t["choices"]}
    out += [f"        ({text(a['name'])}, ModeAction.{a['pascal']}, "
            f"[{', '.join('ModeType.Int' if x in choices else cs_type(x) for x in a.get('args', []))}]),"
            for a in t["actions"]]
    out += ["    ];", "",
            "    /// <summary>The actions that need a running step, which game_start refuses.</summary>",
            "    public static readonly IReadOnlySet<ModeAction> ActionsNeedingAStep =",
            "        new HashSet<ModeAction>", "        {"]
    out += [f"            ModeAction.{a['pascal']}," for a in t["actions"] if a.get("needs_step")]
    out += ["        };", "",
            "    /// <summary>The choices: an argument of one takes one of its names, its value the name's place.</summary>",
            "    public static readonly IReadOnlyDictionary<string, IReadOnlyList<string>> Choices =",
            "        new Dictionary<string, IReadOnlyList<string>>", "        {"]
    out += [f"            [{text(c['name'])}] = [{', '.join(text(v) for v in c['values'])}]," for c in t["choices"]]
    out += ["        };", "",
            "    /// <summary>The actions' arguments that take a choice: (action, argument) to the choice's name.</summary>",
            "    public static readonly IReadOnlyDictionary<(ModeAction Action, int Argument), string> ActionChoices =",
            "        new Dictionary<(ModeAction Action, int Argument), string>", "        {"]
    out += [f"            [(ModeAction.{a['pascal']}, {i})] = {text(x)},"
            for a in t["actions"] for i, x in enumerate(a.get("args", [])) if x in choices]
    out += ["        };", "",
            "    /// <summary>The actions written with a word between their first two arguments in place of a comma.</summary>",
            "    public static readonly IReadOnlyDictionary<ModeAction, string> ActionJoins =",
            "        new Dictionary<ModeAction, string>", "        {"]
    out += [f"            [ModeAction.{a['pascal']}] = {text(a['join'])}," for a in t["actions"] if "join" in a]
    out += ["        };"]
    # the rule set each word arrived in, where after the first
    for kind, enum, name, what in (("ops", "ModeOp", "Ops", "operations"), ("events", "ModeEvent", "Events", "events"),
                                   ("setups", "ModeSetup", "Setups", "setup words"),
                                   ("seat_reads", "ModeSeatRead", "SeatReads", "reads of a seat"),
                                   ("race_reads", "ModeRaceRead", "RaceReads", "reads of the race"),
                                   ("actions", "ModeAction", "Actions", "actions")):
        out += ["", f"    /// <summary>The {what} that arrived after rule set 1, and the rule set each arrived in.</summary>",
                f"    public static readonly IReadOnlyDictionary<{enum}, int> {name}Since =",
                f"        new Dictionary<{enum}, int>", "        {"]
        out += [f"            [{enum}.{e['name'] if kind == 'ops' else e['pascal']}] = {e['since']}," for e in t[kind] if e["since"] > 1]
        out += ["        };"]
    out += ["", "    /// <summary>The values a setup word's argument took after the word itself arrived: (word, argument, value) to",
            "    /// the rule set.</summary>",
            "    public static readonly IReadOnlyDictionary<(ModeSetup Word, int Argument, int Value), int> SetupValuesSince =",
            "        new Dictionary<(ModeSetup Word, int Argument, int Value), int>", "        {"]
    out += [f"            [(ModeSetup.{s['pascal']}, {i}, {a['always']})] = {a['always_since']},"
            for s in t["setups"] for i, a in enumerate(s.get("args", [])) if a.get("always_since", s["since"]) > s["since"]]
    out += ["        };", "}", ""]
    return "\n".join(out)
