"""The C++ header generate.py writes: a struct per packet, Encode and a Decode per packet (on the body, as the
session's Handle reads it), and Decode of a whole datagram. Header-only, standard library only, C++20."""

import re

TYPES = {"u8": "std::uint8_t", "u32": "std::uint32_t", "u64": "std::uint64_t", "i64": "std::int64_t",
         "records": "std::vector<std::uint8_t>"}
GENERATED = "// Generated by protocol/generate.py from protocol/relay.toml. Do not edit."


def upper(key):
    return key.upper()


def comment(text, indent=""):
    """A doc string as // lines of at most 120 characters."""
    out, line = [], f"{indent}//"
    for word in text.split():
        if len(line) + 1 + len(word) > 120:
            out.append(line)
            line = f"{indent}//"
        line += " " + word
    return out + [line]


def constants(protocol):
    mark = ", ".join(f"'{c}'" for c in protocol["mark"])
    drives = ", ".join(f"0x{b:02X}" for b in protocol["ai_drives"])
    out = [f"inline constexpr std::uint8_t VERSION = {protocol['version']};",
           f"inline constexpr std::array<std::uint8_t, {len(protocol['mark'])}> MARK = {{{mark}}};"]
    for key in ("header_size", "record_size", "max_frames_per_packet", "max_payload", "key_size"):
        out.append(f"inline constexpr std::size_t {upper(key)} = {protocol[key]};")
    for group in protocol["flags"]:
        for v in group["values"]:
            name = re.sub(r"(?<!^)(?=[A-Z])", "_", v["name"]).upper()
            out.append(f"inline constexpr {TYPES[group['type']]} {group['cxx_prefix']}{name} = {v['value']};  // {group['name']}")
    out.append(f"inline constexpr std::array<std::uint8_t, {len(protocol['ai_drives'])}> AI_DRIVES = {{{drives}}};"
               "  // the game's AI keeps the seat")
    return out


def structs(packets):
    out = ["", "enum class Type : std::uint8_t", "{"]
    out += [f"  {p.name} = {p.type}," for p in packets]
    out += ["};"]
    for p in packets:
        out += [""] + comment(p.doc) + [f"struct {p.name}", "{"]
        for f in p.fields:
            if f.optional:
                out.append(f"  std::optional<{TYPES[f.type]}> {f.snake};")
            elif f.type == "records":
                out.append(f"  {TYPES[f.type]} {f.snake};")
            else:
                out.append(f"  {TYPES[f.type]} {f.snake} = 0;")
        out.append("};")
    return out + ["", f"using Packet = std::variant<{', '.join(p.name for p in packets)}>;"]


def helpers():
    return ["", "namespace detail", "{",
            "inline std::vector<std::uint8_t> Start(Type type, std::size_t body)", "{",
            "  std::vector<std::uint8_t> out(MARK.begin(), MARK.end());",
            "  out.reserve(HEADER_SIZE + body);", "  out.push_back(VERSION);",
            "  out.push_back(static_cast<std::uint8_t>(type));", "  return out;", "}",
            "inline void Put(std::vector<std::uint8_t>& out, std::uint64_t v, int bytes)", "{",
            "  for (int i = bytes - 1; i >= 0; --i)", "    out.push_back(static_cast<std::uint8_t>(v >> (8 * i)));", "}",
            "inline std::uint64_t Get(const std::uint8_t* p, int bytes)", "{", "  std::uint64_t v = 0;",
            "  for (int i = 0; i < bytes; ++i)", "    v = v << 8 | p[i];", "  return v;", "}",
            "}  // namespace detail"]


def put(f, value):
    if f.type == "i64":
        value = f"static_cast<std::uint64_t>({value})"
    return f"detail::Put(out, {value}, {f.size});"


def get(f):
    return f"static_cast<{TYPES[f.type]}>(detail::Get(body + {f.offset}, {f.size}))"


def encoder(p):
    out = ["", f"inline std::vector<std::uint8_t> Encode(const {p.name}& p)", "{",
           f"  auto out = detail::Start(Type::{p.name}, {p.head});"]
    for f in p.fixed:
        if f.optional:
            out += [f"  if (p.{f.snake})", f"    {put(f, '*p.' + f.snake)}"]
        else:
            out.append(f"  {put(f, 'p.' + f.snake)}")
    if p.records:
        out.append(f"  out.insert(out.end(), p.{p.records.snake}.begin(), p.{p.records.snake}.end());")
    return out + ["  return out;", "}"]


def decoder(p):
    out = ["", f"inline std::optional<{p.name}> Decode{p.name}(const std::uint8_t* body, std::size_t len)", "{"]
    if p.optional:
        out += [f"  if (len != {p.head} && len != {p.head + p.optional.size})", "    return std::nullopt;"]
    elif p.records:
        r = p.records
        per = f" * static_cast<std::size_t>(std::popcount({get(r.seats)}))" if r.seats else ""
        out += [f"  if (len < {p.head})", "    return std::nullopt;",
                f"  const std::size_t count = body[{r.count.offset}];",
                f"  if (len != {p.head} + count{per} * RECORD_SIZE)", "    return std::nullopt;"]
    else:
        out += [f"  if (len != {p.head})", "    return std::nullopt;"]
    out.append(f"  {p.name} p;")
    for f in p.fixed:
        if f.optional:
            out += [f"  if (len == {p.head + f.size})", f"    p.{f.snake} = {get(f)};"]
        else:
            out.append(f"  p.{f.snake} = {get(f)};")
    if p.records:
        out.append(f"  p.{p.records.snake}.assign(body + {p.head}, body + len);")
    return out + ["  return p;", "}"]


def whole(protocol, packets):
    n = len(protocol["mark"])
    marks = " || ".join(f"data[{i}] != MARK[{i}]" for i in range(n))
    keyed = " ||\n         ".join(f"type == Type::{p.name}" for p in packets if p.from_relay)
    out = ["", "// A packet the relay sends a game: its body opens with the seat's key (KEY_SIZE bytes).",
           "inline constexpr bool FromRelay(Type type)", "{", f"  return {keyed};", "}", "", "// The version of a packet from another version of the game or relay (none: this version, or no relay "
           "packet).", "inline std::optional<std::uint8_t> ForeignVersion(const std::uint8_t* data, std::size_t len)",
           "{", f"  if (len < HEADER_SIZE || {marks} || data[{n}] == VERSION)", "    return std::nullopt;",
           f"  return data[{n}];", "}", "",
           "// A whole datagram; none for anything malformed or foreign.",
           "inline std::optional<Packet> Decode(const std::uint8_t* data, std::size_t len)", "{",
           f"  if (len < HEADER_SIZE || {marks} || data[{n}] != VERSION)", "    return std::nullopt;",
           "  const std::uint8_t* body = data + HEADER_SIZE;", "  const std::size_t n = len - HEADER_SIZE;",
           f"  switch (static_cast<Type>(data[{n + 1}]))", "  {"]
    for p in packets:
        out += [f"  case Type::{p.name}:", f"    if (auto p = Decode{p.name}(body, n))", "      return Packet{std::move(*p)};",
                "    break;"]
    out += ["  default:", "    break;", "  }", "  return std::nullopt;", "}", "",
            "inline std::vector<std::uint8_t> Encode(const Packet& packet)", "{",
            "  return std::visit([](const auto& p) { return Encode(p); }, packet);", "}"]
    return out


def emit(protocol, packets):
    space = protocol["codec"]["cxx"]["namespace"]
    out = [GENERATED, "// The relay protocol's packets: a struct per packet, its encoder, and its decoder on the body (what",
           "// follows the header's mark, version and type). Every number big-endian; a body of another length decodes",
           "// to nothing.", "// SPDX-License-Identifier: GPL-3.0-or-later", "", "#pragma once", ""]
    out += [f"#include <{h}>" for h in ("array", "bit", "cstddef", "cstdint", "optional", "utility", "variant", "vector")]
    out += ["", f"namespace {space}", "{"] + constants(protocol) + structs(packets) + helpers()
    for p in packets:
        out += encoder(p) + decoder(p)
    out += whole(protocol, packets) + [f"}}  // namespace {space}"]
    return "\n".join(out) + "\n"


def describe(f):
    if f.optional:
        return f'" {f.name}=" + (p.{f.snake} ? std::to_string(*p.{f.snake}) : std::string("-"))'
    if f.type == "records":
        return f'" {f.name}=" + Hex(p.{f.snake})'
    value = f"static_cast<unsigned>(p.{f.snake})" if f.type == "u8" else f"p.{f.snake}"
    return f'" {f.name}=" + std::to_string({value})'


def emit_describe(protocol, packets):
    """For the round-trip test: a packet as one line of text, as the vectors file holds it (protocol/tests)."""
    space = protocol["codec"]["cxx"]["namespace"]
    out = [GENERATED, "// For the round-trip test only: a packet as the line the vectors file holds (Kind Field=value ...;",
           "// records in lowercase hexadecimal, an absent optional field as -).", "", "#pragma once", "",
           '#include "relay_packets.g.h"', "", "#include <string>", "", f"namespace {space}::test", "{",
           "inline std::string Hex(const std::vector<std::uint8_t>& bytes)", "{",
           "  static constexpr char digits[] = \"0123456789abcdef\";", "  std::string out;",
           "  for (const std::uint8_t b : bytes)", "  {", "    out += digits[b >> 4];", "    out += digits[b & 15];", "  }",
           "  return out;", "}"]
    for p in packets:
        parts = " + ".join(describe(f) for f in p.cs_fields)   # in the C# record's order, as the harness writes it
        out += ["", f"inline std::string Describe(const {p.name}& p)", "{", f'  return std::string("{p.name}") + {parts};',
                "}"]
    out += ["", "inline std::string Describe(const Packet& packet)", "{",
            "  return std::visit([](const auto& p) { return Describe(p); }, packet);", "}",
            f"}}  // namespace {space}::test"]
    return "\n".join(out) + "\n"
