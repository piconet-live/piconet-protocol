"""The stat pack's C++ tables generate.py writes: generated/stat_ranges.g.h (the ranges, fzgx::stats::RULES) and
generated/const_ranges.g.h (the code constants, fzgx::consts::CONSTANTS), with their types. The runner's
port/core/src/stat_ranges.h and const_ranges.h include them and hold their places to the facts table. Header-only,
standard library only, C++20."""
from stats import literal

GENERATED = "// Generated by protocol/generate.py from protocol/stats.toml. Do not edit."
CXX_KIND = {"number": "Number", "bytes": "Bytes", "points": "Points"}


def number(value, single):
    text = literal(value, single)
    return "1.7976931348623157e308" if text is None else text


def emit_ranges(tables):
    rows = [f'    {{0x{r.at:02X}, Kind::{CXX_KIND[r.kind]}, "{r.name}", {number(r.low, True)}, {number(r.high, True)}, '
            f'{"true" if r.below else "false"}, {number(r.z_least, True)}}},' for r in tables.rules]
    return "\n".join([
        GENERATED,
        "// What a stat pack may hold of the car data: for every word of a block a pack can change, the range the",
        "// game's physics is safe in (protocol/stats.toml; the runner's port/core/src/stat_ranges.h says what the",
        "// rows rest on).",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        f"namespace {tables.codec['cxx']['ranges_namespace']}",
        "{",
        "enum class Kind : std::uint8_t",
        "{",
        "  Number,  // one number",
        "  Bytes,   // the word at the facts' CAR_BYTES_AT: two bytes, then two that are zero",
        "  Points,  // four points of three numbers each: X, Y, Z",
        "};",
        "",
        "struct Rule",
        "{",
        "  std::uint8_t at;   // the first word's offset in a block",
        "  Kind kind;",
        "  const char* name;  // the stat's name in a pack file (the launcher's MachineStat where it has one)",
        "  float low;         // a number is at least this",
        "  float high;        // and at most this, or less than this when `below`",
        "  bool below;",
        "  float z_least;     // Points: in a machine a Z is at least this far from 0 (0: no such rule)",
        "};",
        "",
        "// By offset. Bytes: `high` is the most the second byte may be; the first is any byte. Points: `low` is -`high`.",
        f"inline constexpr std::array<Rule, {len(tables.rules)}> RULES = {{{{",
        *rows,
        "}};",
        f"}}  // namespace {tables.codec['cxx']['ranges_namespace']}",
        ""])


def emit_constants(tables):
    rows = [f'    {{"{c.name}", Kind::{kind}, 0x{at:02X}, 0x{stock:08X}, {number(low, False)}, {number(high, False)}}},'
            for c, slot, kind, at, stock, low, high in tables.slots]
    return "\n".join([
        GENERATED,
        "// What a stat pack may hold beside the car data: the allowed words of the game's code constants, by slot",
        "// (protocol/stats.toml; the runner's port/core/src/const_ranges.h names every reader of each).",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        f"namespace {tables.codec['cxx']['constants_namespace']}",
        "{",
        "enum class Kind : std::uint8_t",
        "{",
        "  Number32,      // one 32-bit number",
        "  Number64High,  // the high word of a 64-bit number; the next slot is its low word, and a pack holds both or neither",
        "  Number64Low,",
        "};",
        "",
        "struct Constant",
        "{",
        "  const char* name;  // in a pack file: `constant NAME VALUE` (a double's two slots share it)",
        "  Kind kind;",
        "  std::uint32_t at;     // the word's offset in a seat's constants record",
        "  std::uint32_t stock;  // the game's own bits",
        "  double low;           // a value is at least this",
        "  double high;          // and at most this",
        "};",
        "",
        "// By slot.",
        f"inline constexpr std::array<Constant, {len(rows)}> CONSTANTS = {{{{",
        *rows,
        "}};",
        f"}}  // namespace {tables.codec['cxx']['constants_namespace']}",
        ""])
