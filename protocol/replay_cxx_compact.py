"""The compact replay file's C++ header generate.py writes (generated/replay_compact.g.h; replay.toml's [compact],
version 8): the fold, which steps keep a whole checksum, the compare of a step's checksum, and Compact and Expand (a
recording to the compact file and back) through liblzma (xz-utils). Apart from replay_file.g.h so that only what
reads or writes a compact file needs liblzma. Header-only, C++20."""

GENERATED = "// Generated by protocol/generate.py from protocol/replay.toml. Do not edit."


def mark(text):
    return "{" + ", ".join(f"'{c}'" for c in text) + "}"


CODE = r'''
#pragma once

#include <lzma.h>

#include <array>
#include <cstddef>
#include <cstdint>
#include <cstring>
#include <string>
#include <vector>

#include "replay_file.g.h"

namespace @NS@
{
// The compact file a recording becomes when it ends: the mark, u16 COMPACT_VERSION, u16 the recording's own version,
// then the header (xz), frames, lineup, inputs (u32 steps, xz of the records in columns) and checksums (xz) parts,
// each its mark, u32 its length and its bytes, then the results as in every version (formats.md section 1).
inline constexpr std::uint16_t COMPACT_VERSION = @VERSION@;
inline constexpr std::size_t COMPACT_HEAD = 8;  // the mark, the version, the recording's version
inline constexpr std::array<char, 4> HEADER_MARK = @HEADER_MARK@;
inline constexpr std::array<char, 4> INPUTS_MARK = @INPUTS_MARK@;
inline constexpr std::array<char, 4> CHECKSUMS_MARK = @CHECKSUMS_MARK@;
inline constexpr std::size_t FULL_EVERY = @FULL_EVERY@;  // every FULL_EVERY-th step and the last keep their whole checksum
inline constexpr std::uint32_t XZ_PRESET = @PRESET@;  // with LZMA_PRESET_EXTREME
inline constexpr std::uint32_t DICT_MIN = @DICT_MIN@;
inline constexpr std::uint32_t DICT_MAX = @DICT_MAX@;
inline constexpr std::uint64_t XZ_MEMLIMIT = @MEMLIMIT@;

// Whether a reader of the game takes a file of this version: a recording's (Played), or the compact file.
constexpr bool PlayedFile(std::uint32_t version)
{
  return Played(version) || version == COMPACT_VERSION;
}

// A step's checksum as the compact file keeps it between its whole ones: its four bytes XORed.
constexpr std::uint8_t Fold(std::uint32_t c)
{
  return static_cast<std::uint8_t>(c ^ c >> 8 ^ c >> 16 ^ c >> 24);
}

// Whether a compact file of `steps` steps keeps step's whole checksum.
constexpr bool IsFull(std::size_t step, std::size_t steps)
{
  return step % FULL_EVERY == 0 || step + 1 == steps;
}

// A step's recorded checksum against the one a game computed: the whole word where the file keeps it (`full`),
// else its folded byte (a compact file's other steps hold the byte, which is its own fold).
constexpr bool ChecksumMatches(std::uint32_t recorded, bool full, std::uint32_t computed)
{
  return full ? recorded == computed : Fold(recorded) == Fold(computed);
}

namespace detail
{
// data as one xz stream: LZMA2 at XZ_PRESET with the extreme flag, a dictionary of data's size, a CRC32 check.
inline bool Xz(const std::uint8_t* data, std::size_t size, std::vector<std::uint8_t>* out)
{
  lzma_options_lzma options;
  if (lzma_lzma_preset(&options, XZ_PRESET | LZMA_PRESET_EXTREME))
    return false;
  options.dict_size = static_cast<std::uint32_t>(size < DICT_MIN ? DICT_MIN : size > DICT_MAX ? DICT_MAX : size);
  const lzma_filter filters[] = {{LZMA_FILTER_LZMA2, &options}, {LZMA_VLI_UNKNOWN, nullptr}};
  lzma_stream s = LZMA_STREAM_INIT;
  if (lzma_stream_encoder(&s, filters, LZMA_CHECK_CRC32) != LZMA_OK)
    return false;
  out->resize(lzma_stream_buffer_bound(size));
  s.next_in = data;
  s.avail_in = size;
  s.next_out = out->data();
  s.avail_out = out->size();
  const lzma_ret ret = lzma_code(&s, LZMA_FINISH);
  out->resize(s.total_out);
  lzma_end(&s);
  return ret == LZMA_STREAM_END;
}

// One xz stream, whole and checked, of at most `most` bytes (exactly `most` with exact), and nothing after it.
inline bool Unxz(const std::uint8_t* data, std::size_t size, std::size_t most, bool exact, std::vector<std::uint8_t>* out)
{
  lzma_stream s = LZMA_STREAM_INIT;
  if (lzma_stream_decoder(&s, XZ_MEMLIMIT, 0) != LZMA_OK)
    return false;
  out->resize(most + 1);
  s.next_in = data;
  s.avail_in = size;
  s.next_out = out->data();
  s.avail_out = out->size();
  const lzma_ret ret = lzma_code(&s, LZMA_FINISH);
  const bool whole = ret == LZMA_STREAM_END && s.avail_in == 0 && s.total_out <= most && (!exact || s.total_out == most);
  out->resize(s.total_out);
  lzma_end(&s);
  return whole;
}

inline void Section(std::vector<std::uint8_t>& out, const std::array<char, 4>& mark, const std::uint8_t* body,
                    std::size_t size, std::size_t more = 0)
{
  const std::size_t at = out.size();
  out.resize(at + 8);
  std::memcpy(out.data() + at, mark.data(), 4);
  Put32(out.data() + at + 4, static_cast<std::uint32_t>(size + more));  // (more: bytes the caller appends)
  out.insert(out.end(), body, body + size);
}
}  // namespace detail

// A whole recording of a version the game plays (header, frames, lineup of LINEUP_SIZE, one whole step or more,
// results or none) as the compact file; false, with why, for any other.
inline bool Compact(const std::uint8_t* data, std::size_t size, std::vector<std::uint8_t>* out, std::string* why)
{
  const Parts p = Parse(data, size);
  if (!p.marked || !Played(p.version) || !p.frames_marked || !p.lineup || p.lineup_length != LINEUP_SIZE ||
      p.steps_at > p.steps_end || p.Steps() == 0 || !p.Whole())
  {
    *why = "not a whole recording";
    return false;
  }
  const std::size_t n = p.Steps(), width = p.Row();
  std::vector<std::uint8_t> planes(n * width), sums;
  sums.reserve(n + 4 * (n / FULL_EVERY + 2));
  for (std::size_t t = 0; t < n; ++t)
  {
    const std::uint8_t* row = data + p.StepAt(t);
    for (std::size_t j = 0; j < width; ++j)
      planes[j * n + t] = row[j];
    sums.push_back(Fold(detail::Get32(row + width)));
  }
  for (std::size_t t = 0; t < n; ++t)
    if (IsFull(t, n))
      sums.insert(sums.end(), data + p.StepAt(t) + width, data + p.StepAt(t) + width + CHECKSUM_SIZE);
  std::vector<std::uint8_t> header, inputs, checksums;
  if (!detail::Xz(data + p.HeaderAt(), p.header_length, &header) || !detail::Xz(planes.data(), planes.size(), &inputs) ||
      !detail::Xz(sums.data(), sums.size(), &checksums))
  {
    *why = "xz failed";
    return false;
  }
  out->assign(COMPACT_HEAD, 0);
  std::memcpy(out->data(), MARK.data(), 4);
  detail::Put16(out->data() + 4, COMPACT_VERSION);
  detail::Put16(out->data() + 6, p.version);
  detail::Section(*out, HEADER_MARK, header.data(), header.size());
  std::uint8_t frames[8];
  detail::Put32(frames, p.mask);
  detail::Put32(frames + 4, p.seat);
  detail::Section(*out, FRAMES_MARK, frames, sizeof frames);
  detail::Section(*out, LINEUP_MARK, data + p.lineup_at, p.lineup_length);
  std::uint8_t steps[4];
  detail::Put32(steps, static_cast<std::uint32_t>(n));
  detail::Section(*out, INPUTS_MARK, steps, 4, inputs.size());
  out->insert(out->end(), inputs.begin(), inputs.end());
  detail::Section(*out, CHECKSUMS_MARK, checksums.data(), checksums.size());
  if (p.results)
    out->insert(out->end(), data + p.results_at, data + size);
  return true;
}

// A compact file as the recording it was made of (its own version), but that a step whose whole checksum the compact
// file does not keep holds its folded byte (IsFull, ChecksumMatches); false, with why, for a file that is not one.
inline bool Expand(const std::uint8_t* data, std::size_t size, std::vector<std::uint8_t>* out, std::string* why)
{
  if (size < COMPACT_HEAD || std::memcmp(data, MARK.data(), 4) != 0 || detail::Get16(data + 4) != COMPACT_VERSION ||
      size > MAX_BYTES)
  {
    *why = "not a compact replay";
    return false;
  }
  const std::uint16_t race = detail::Get16(data + 6);
  if (!Played(race))
  {
    *why = "a recording of version " + std::to_string(race) + ", which the game does not play";
    return false;
  }
  std::size_t end = size;
  if (size - COMPACT_HEAD >= RESULTS_TAIL && std::memcmp(data + size - 4, RESULTS_MARK.data(), 4) == 0)
  {
    const std::size_t length = detail::Get32(data + size - 8);
    if (length + RESULTS_TAIL <= size - COMPACT_HEAD)
      end = size - RESULTS_TAIL - length;
  }
  const std::array<char, 4>* marks[] = {&HEADER_MARK, &FRAMES_MARK, &LINEUP_MARK, &INPUTS_MARK, &CHECKSUMS_MARK};
  const std::uint8_t* part[5];
  std::size_t length[5];
  std::size_t at = COMPACT_HEAD;
  for (int i = 0; i < 5; ++i)
  {
    if (end - at < 8 || std::memcmp(data + at, marks[i]->data(), 4) != 0 || detail::Get32(data + at + 4) > end - at - 8)
    {
      *why = "a part missing, out of its place or longer than the file";
      return false;
    }
    length[i] = detail::Get32(data + at + 4);
    part[i] = data + at + 8;
    at += 8 + length[i];
  }
  if (at != end || length[1] != FRAMES_SIZE - 4 || length[3] < 4)
  {
    *why = "bytes between the parts and the results, or a frames or inputs part of another size";
    return false;
  }
  const std::uint32_t mask = detail::Get32(part[1]), seat = detail::Get32(part[1] + 4);
  const std::size_t n = detail::Get32(part[3]), width = static_cast<std::size_t>(std::popcount(mask)) * RECORD_SIZE;
  if (width == 0 || n == 0 || n > MAX_STEPS)
  {
    *why = "no player seat, or no step, or more than MAX_STEPS";
    return false;
  }
  std::size_t full = 0;
  for (std::size_t t = 0; t < n; ++t)
    full += IsFull(t, n) ? 1 : 0;
  std::vector<std::uint8_t> header, planes, sums;
  if (!detail::Unxz(part[0], length[0], MAX_JSON, false, &header) ||
      !detail::Unxz(part[3] + 4, length[3] - 4, n * width, true, &planes) ||
      !detail::Unxz(part[4], length[4], n + 4 * full, true, &sums))
  {
    *why = "an xz part that does not read, is cut, or holds another length";
    return false;
  }
  *out = EncodeStartAs(race, std::string_view(reinterpret_cast<const char*>(header.data()), header.size()), mask, seat);
  const std::size_t lineup = out->size();
  out->resize(lineup + 8);
  std::memcpy(out->data() + lineup, LINEUP_MARK.data(), 4);
  detail::Put32(out->data() + lineup + 4, static_cast<std::uint32_t>(length[2]));
  out->insert(out->end(), part[2], part[2] + length[2]);
  out->reserve(out->size() + n * (width + CHECKSUM_SIZE) + (size - end));
  std::vector<std::uint8_t> row(width);
  std::size_t k = 0;
  for (std::size_t t = 0; t < n; ++t)
  {
    for (std::size_t j = 0; j < width; ++j)
      row[j] = planes[j * n + t];
    std::uint32_t sum = sums[t];
    if (IsFull(t, n))
    {
      sum = detail::Get32(sums.data() + n + 4 * k++);
      if (Fold(sum) != sums[t])
      {
        *why = "step " + std::to_string(t) + "'s whole checksum and its byte disagree";
        return false;
      }
    }
    EncodeStep(*out, row.data(), width, sum);
  }
  out->insert(out->end(), data + end, data + size);
  return true;
}
}  // namespace @NS@
'''


def emit(s):
    c = s["compact"]
    text = CODE
    for key, value in (("NS", s["codec"]["cxx"]["namespace"]), ("VERSION", c["version"]),
                       ("HEADER_MARK", mark(c["header_mark"])), ("INPUTS_MARK", mark(c["inputs_mark"])),
                       ("CHECKSUMS_MARK", mark(c["checksums_mark"])), ("FULL_EVERY", c["full_every"]),
                       ("PRESET", c["preset"]), ("DICT_MIN", c["dict_min"]), ("DICT_MAX", c["dict_max"]),
                       ("MEMLIMIT", c["memlimit"])):
        text = text.replace(f"@{key}@", str(value))
    return GENERATED + "\n// The compact replay file (version " + str(c["version"]) + \
        "): protocol/formats.md section 1.\n// SPDX-License-Identifier: GPL-3.0-or-later\n" + text
