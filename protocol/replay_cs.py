"""The replay file's C# reader generate.py writes: the constants (marks, versions, sizes, limits, the JSON members'
keys), the version a race's features make, the lineup, the results' entries read from their JSON, and ReplayParts: a
file's parts as far as the file has them, read from the file's head and its end without the steps (a folder of
replays is listed at the launcher's start). It judges nothing: each caller keeps its own refusals."""

GENERATED = "// Generated by protocol/generate.py from protocol/replay.toml. Do not edit."
TYPES = {"u8": "byte", "i16": "short", "u16": "ushort", "u32": "uint"}


def int_type(m):
    return "int" if m.low >= -0x80000000 and m.high <= 0x7FFFFFFF else "long"


def member_type(m):
    t = "bool" if m.type == "bool" else int_type(m)
    return t + ("?" if m.null else "")


def format_class(s, prefix):
    v = s["versions"]
    out = ["", f"/// <summary>The replay file's constants (protocol/replay.toml; formats.md section 1).</summary>",
           f"public static class {prefix}Format", "{"]
    for name, text in (("Mark", s["mark"]), ("FramesMark", s["frames_mark"]), ("LineupMark", s["lineup_mark"]),
                       ("ResultsMark", s["results_mark"])):
        out.append(f"    public static ReadOnlySpan<byte> {name} => \"{text}\"u8;")
    out.append("")
    for x in v:
        out += [f"    /// <summary>Version {x['number']}: {x['doc']}.</summary>",
                f"    public const int Version{x['name']} = {x['number']};"]
    out += [f"    /// <summary>The only version the game writes.</summary>",
            f"    public const int VersionWritten = {s['written']};", "",
            f"    public const int HeadSize = {s['head_size']};", f"    public const int FramesSize = {s['frames_size']};",
            f"    public const int LineupSize = {s['lineup_size']};", f"    public const int LineupLeast = {s['lineup_least']};",
            f"    public const int RecordSize = {s['record_size']};", f"    public const int ChecksumSize = {s['checksum_size']};",
            "    public const int ResultsTail = 8;", f"    public const long MaxBytes = {s['max_bytes']};",
            f"    public const long MaxSteps = {s['max_steps']};", f"    public const uint MaxJson = {s['max_json']};",
            f"    public const int MaxSeats = {s['max_seats']};", "",
            "    /// <summary>Whether the game plays a file of this version.</summary>",
            "    public static bool Plays(int version) => version is " + " or ".join(str(x["number"]) for x in v) + ";", "",
            "    /// <summary>The version a race of these features is, and the only one its file may be: the highest whose",
            "    /// feature it holds, else the first.</summary>",
            f"    public static int VersionOf({prefix}Features f) =>"]
    arms = [f"f.{x['name']} ? Version{x['name']}" for x in reversed(v[1:])]
    out.append("        " + " : ".join(arms) + f" : Version{v[0]['name']};")
    for part, cls in (("header", "Header"), ("result", "Result")):
        out += ["", f"    /// <summary>The {part}'s JSON members.</summary>", f"    public static class {cls}", "    {"]
        for m in s[part]:
            out.append(f"        public const string {m.name} = \"{m.key}\";")
            if m.type == "int" and part == "header":
                out.append(f"        public const long {m.name}Low = {m.low};")
                out.append(f"        public const long {m.name}High = {m.high};")
                if m.default is not None:
                    out.append(f"        public const long {m.name}Default = {m.default};")
        out.append("    }")
    # the lineup
    out += ["", "    /// <summary>The lineup's block (its first <see cref=\"LineupSize\"/> bytes at most; the rest reads 0).</summary>",
            f"    public static {prefix}Lineup DecodeLineup(ReadOnlySpan<byte> block)", "    {",
            "        Span<byte> b = stackalloc byte[LineupSize];", "        b.Clear();",
            "        block[..Math.Min(block.Length, LineupSize)].CopyTo(b);"]
    args = []
    for f in s["lineup"]:
        if f.type == "pad":
            continue
        one = {"u8": "b[{at}]", "i16": "BinaryPrimitives.ReadInt16BigEndian(b[({at})..])"}[f.type]
        size = f.size // (f.count or 1)
        if f.count:
            out.append(f"        var {f.snake} = new {TYPES[f.type]}[{f.count}];")
            out.append(f"        for (var i = 0; i < {f.count}; i++)")
            out.append("        {")
            out.append(f"            {f.snake}[i] = {one.format(at=f'{f.offset} + (i * {size})')};")
            out.append("        }")
        else:
            out.append(f"        var {f.snake} = {one.format(at=f.offset)};")
        args.append(f.snake)
    out += [f"        return new {prefix}Lineup({', '.join(args)});", "    }"]
    # the results
    out += ["", f"    /// <summary>The results' entries from their JSON ({{\"{s['results_list']}\": [...]}}); a member missing or of",
            "    /// another kind throws (KeyNotFoundException, InvalidOperationException, JsonException).</summary>",
            f"    public static List<{prefix}Result> ParseResults(byte[] json)", "    {",
            "        using var doc = JsonDocument.Parse(json);", f"        var list = new List<{prefix}Result>();",
            f"        foreach (var e in doc.RootElement.GetProperty(\"{s['results_list']}\").EnumerateArray())", "        {"]
    values = []
    for m in s["result"]:
        if m.type == "bool":
            get = f"e.GetProperty(Result.{m.name}).GetBoolean()"
        else:
            g = "GetInt32" if int_type(m) == "int" else "GetInt64"
            get = (f"e.GetProperty(Result.{m.name}) is {{ ValueKind: JsonValueKind.Number }} {m.snake} ? {m.snake}.{g}() : "
                   f"({int_type(m)}?)null") if m.null else f"e.GetProperty(Result.{m.name}).{g}()"
        values.append(get)
    out.append(f"            list.Add(new {prefix}Result(")
    out += [f"                {v}{',' if i < len(values) - 1 else '));'}" for i, v in enumerate(values)]
    out += ["        }", "        return list;", "    }", "}"]
    return out


def records(s, prefix):
    v = s["versions"]
    out = ["", "/// <summary>What a race holds that a replay's version says (replay.toml's features).</summary>",
           f"public readonly record struct {prefix}Features(" + ", ".join(f"bool {x['name']} = false" for x in v[1:]) + ");",
           "", "/// <summary>The lineup's block: " + s["lineup_doc"] + ".</summary>",
           f"public sealed record {prefix}Lineup(" +
           ", ".join(f"{TYPES[f.type]}{'[]' if f.count else ''} {f.name}" for f in s["lineup"] if f.type != "pad") + ");",
           "", "/// <summary>A racer's entry of a replay's results.</summary>",
           f"public sealed record {prefix}Result(" + ", ".join(f"{member_type(m)} {m.name}" for m in s["result"]) + ");"]
    return out


def parts(prefix):
    p = prefix
    return ["", "/// <summary>A replay file's parts, as far as the file has them: each read only when the one before it is whole,",
            "/// the steps never (only where they begin and end). A part the file does not have is left as it starts (false,",
            "/// null, 0), and nothing after it is read. It judges nothing: which version, which mark, which game make a replay",
            "/// is each caller's question.</summary>",
            f"public sealed class {p}Parts", "{",
            "    /// <summary>The file begins with the head, its first four bytes the mark.</summary>",
            "    public bool Marked { get; private set; }", "",
            "    public int Version { get; private set; }", "",
            "    /// <summary>The header's length as the file names it.</summary>",
            "    public uint HeaderLength { get; private set; }", "",
            f"    /// <summary>The header's JSON; null when it is named longer than {p}Format.MaxJson (not read) or the file",
            "    /// ends before it does.</summary>",
            "    public byte[]? Header { get; private set; }", "",
            "    /// <summary>The frames' part (after the header) is there; whether it begins with its mark.</summary>",
            "    public bool Frames { get; private set; }", "",
            "    public bool FramesMarked { get; private set; }", "",
            "    /// <summary>The player seats whose records a step holds; the recorder's seat.</summary>",
            "    public uint Mask { get; private set; }", "",
            "    public uint Seat { get; private set; }", "",
            "    /// <summary>A lineup's mark and length after the frames' part; the block's length the file names.</summary>",
            "    public bool Lineup { get; private set; }", "",
            "    public uint LineupLength { get; private set; }", "",
            "    /// <summary>The lineup's block's first byte.</summary>",
            "    public long LineupAt { get; private set; }", "",
            f"    /// <summary>The results' JSON at the file's end (null: none, or longer than {p}Format.MaxJson).</summary>",
            "    public byte[]? Results { get; private set; }", "",
            "    /// <summary>Where the steps begin (after the lineup, or the frames' part) and end (the results, or the file's",
            "    /// end), and the file's length.</summary>",
            "    public long StepsAt { get; private set; }", "",
            "    public long StepsEnd { get; private set; }", "",
            "    public long Length { get; private set; }", "",
            "    /// <summary>The file could not be opened, or reading it failed: of what comes after the parts read, nothing",
            "    /// is known (a file that merely ends early is not this).</summary>",
            "    public bool Failed { get; private set; }", "",
            "    public int Seats => (int)uint.PopCount(Mask);", "",
            f"    public long StepSize => ((long){p}Format.RecordSize * Seats) + {p}Format.ChecksumSize;", "",
            "    public long StepBytes => Math.Max(0, StepsEnd - StepsAt);", "",
            "    /// <summary>The whole steps.</summary>",
            "    public long Steps => Seats == 0 ? 0 : StepBytes / StepSize;", "",
            "    /// <summary>The steps' bytes are whole steps (none at all included).</summary>",
            "    public bool Whole => Frames && Seats != 0 && StepsEnd >= StepsAt && StepBytes % StepSize == 0;", "",
            f"    public static {p}Parts Read(string path)", "    {", f"        var parts = new {p}Parts();",
            "        try", "        {", "            using var file = File.OpenRead(path);", "            parts.ReadFrom(file);", "        }",
            "        catch (Exception e) when (e is IOException or UnauthorizedAccessException or ArgumentException or NotSupportedException",
            "                                       or System.Security.SecurityException)", "        {",
            "            parts.Failed = true;", "        }", "        return parts;", "    }", "",
            "    private void ReadFrom(FileStream file)", "    {",
            f"        Span<byte> head = stackalloc byte[{p}Format.HeadSize];",
            f"        if (file.ReadAtLeast(head, head.Length, throwOnEndOfStream: false) < head.Length || !head[..4].SequenceEqual({p}Format.Mark))",
            "        {", "            return;", "        }",
            "        Marked = true;", "        Version = BinaryPrimitives.ReadUInt16BigEndian(head[4..]);",
            "        HeaderLength = BinaryPrimitives.ReadUInt32BigEndian(head[6..]);",
            f"        if (HeaderLength > {p}Format.MaxJson)", "        {", "            return;", "        }",
            "        var json = new byte[HeaderLength];",
            "        if (file.ReadAtLeast(json, json.Length, throwOnEndOfStream: false) < json.Length)", "        {", "            return;", "        }",
            "        Header = json;",
            f"        Span<byte> frames = stackalloc byte[{p}Format.FramesSize];",
            "        if (file.ReadAtLeast(frames, frames.Length, throwOnEndOfStream: false) < frames.Length)", "        {", "            return;", "        }",
            f"        Frames = true;", f"        FramesMarked = frames[..4].SequenceEqual({p}Format.FramesMark);",
            "        Mask = BinaryPrimitives.ReadUInt32BigEndian(frames[4..]);", "        Seat = BinaryPrimitives.ReadUInt32BigEndian(frames[8..]);",
            "        var framesEnd = file.Position;", "        Length = file.Length;", "        StepsAt = framesEnd;", "        StepsEnd = Length;",
            f"        Span<byte> tail = stackalloc byte[{p}Format.ResultsTail];",
            f"        if (Length - framesEnd >= tail.Length)", "        {",
            "            file.Seek(-tail.Length, SeekOrigin.End);", "            file.ReadExactly(tail);",
            "            var length = BinaryPrimitives.ReadUInt32BigEndian(tail);",
            f"            if (tail[4..].SequenceEqual({p}Format.ResultsMark) && length + (long)tail.Length <= Length - framesEnd && length <= {p}Format.MaxJson)",
            "            {", "                var results = new byte[length];", "                file.Seek(-tail.Length - length, SeekOrigin.End);",
            "                file.ReadExactly(results);", "                Results = results;", "                StepsEnd = Length - tail.Length - length;", "            }",
            "        }",
            "        if (StepsEnd - framesEnd >= 8)", "        {", "            file.Position = framesEnd;",
            "            Span<byte> l = stackalloc byte[8];", "            file.ReadExactly(l);",
            f"            if (l[..4].SequenceEqual({p}Format.LineupMark))", "            {",
            "                Lineup = true;", "                LineupLength = BinaryPrimitives.ReadUInt32BigEndian(l[4..]);",
            "                LineupAt = framesEnd + 8;", "                StepsAt = LineupAt + LineupLength;", "            }", "        }", "    }",
            "}"]


def emit(s):
    p = s["codec"]["csharp"]["prefix"]
    lines = [GENERATED, "#nullable enable", "using System.Buffers.Binary;", "using System.Text.Json;", "",
             f"namespace {s['codec']['csharp']['namespace']};"]
    lines += format_class(s, p) + records(s, p) + parts(p) + [""]
    return "\n".join(lines)
