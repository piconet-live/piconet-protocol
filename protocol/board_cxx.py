"""The status board's C++ header generate.py writes: the constants, the enums and flags, a value struct for every
record and every seqlock block, the offsets, and View: the board's memory read and written through std::atomic_ref
(every word an atomic access; a seqlock block as one group). Header-only, standard library only, C++20."""

from board import SIZES, snake

GENERATED = "// Generated by protocol/generate.py from protocol/board.toml. Do not edit."
TYPES = {"u8": "std::uint8_t", "u16": "std::uint16_t", "u32": "std::uint32_t", "u64": "std::uint64_t",
         "i32": "std::int32_t", "f32": "float"}
WORD = {"u8": "std::uint8_t", "u16": "std::uint16_t", "u32": "std::uint32_t", "u64": "std::uint64_t",
        "i32": "std::int32_t", "f32": "std::uint32_t"}


def comment(text, indent=""):
    out, line = [], f"{indent}//"
    for word in text.split():
        if len(line) + 1 + len(word) > 120:
            out.append(line)
            line = f"{indent}//"
        line += " " + word
    return out + [line] if line.strip() != "//" else out


def upper(name):
    return snake(name).upper()


def value_type(f):
    if f.record:
        return f"std::array<{f.record.name}, {f.count}>"
    if f.type == "bytes":
        return f"std::array<std::uint8_t, {f.size}>"
    if f.enum:
        return f.enum
    return TYPES[f.type]


def struct(name, doc, fields):
    out = [""] + comment(doc) + [f"struct {name}", "{"]
    for f in fields:
        init = "{}" if (f.record or f.type == "bytes" or f.enum) else " = 0"
        line = f"  {value_type(f)} {f.snake}{init};"
        out.append(line + (f"  // {f.doc}" if f.doc and len(line) + len(f.doc) < 116 else ""))
    return out + ["};"]


def load_field(f, base, order, target):
    """Statements that read field f (at base + its offset) into target."""
    at = f"{base} + {f.offset}"
    if f.record:
        return [f"for (std::size_t i = 0; i < {f.count}; ++i)",
                f"  Load{f.record.name}({at} + i * {f.record.size}, &{target}[i], {order});"]
    if f.type == "bytes":
        return [f"for (std::size_t i = 0; i < {f.size // 4}; ++i)",
                f"  Unpack(Load<std::uint32_t>({at} + i * 4, {order}), &{target}[i * 4]);"]
    word = f"Load<{WORD[f.type]}>({at}, {order})"
    if f.type == "f32":
        return [f"{target} = std::bit_cast<float>({word});"]
    if f.enum:
        return [f"{target} = static_cast<{f.enum}>({word});"]
    return [f"{target} = {word};"]


def store_field(f, base, order, source):
    at = f"{base} + {f.offset}"
    if f.record:
        return [f"for (std::size_t i = 0; i < {f.count}; ++i)",
                f"  Store{f.record.name}({at} + i * {f.record.size}, {source}[i], {order});"]
    if f.type == "bytes":
        return [f"for (std::size_t i = 0; i < {f.size // 4}; ++i)",
                f"  Store<std::uint32_t>({at} + i * 4, Pack(&{source}[i * 4]), {order});"]
    if f.type == "f32":
        return [f"Store<std::uint32_t>({at}, std::bit_cast<std::uint32_t>({source}), {order});"]
    if f.enum:
        return [f"Store<{WORD[f.type]}>({at}, static_cast<{WORD[f.type]}>({source}), {order});"]
    return [f"Store<{WORD[f.type]}>({at}, {source}, {order});"]


def indent(lines, by="    "):
    return [by + line for line in lines]


def emit(board, enums, flags, records, blocks):
    ns = board["codec"]["cxx"]["namespace"]
    out = [GENERATED, "// The status board between the launcher and one running game (protocol/board.toml; protocol/formats.md",
           "// section 8). Every word is read and written as an atomic access; a seqlock block is written by one writer.",
           "#pragma once", "", "#include <array>", "#include <atomic>", "#include <bit>", "#include <cstddef>",
           "#include <cstdint>", "", f"namespace {ns}", "{",
           f"inline constexpr std::uint32_t MAGIC = 0x{board['magic_word']:08X};  // \"{board['magic']}\" as its first four bytes",
           f"inline constexpr std::uint32_t VERSION = {board['version']};",
           f"inline constexpr std::size_t SIZE = {board['size']};  // the whole board, in bytes"]
    for e in enums.values():
        out += [""] + comment(e.doc) + [f"enum class {e.name} : {TYPES[e.type]}", "{"]
        out += [f"  {v['name']} = {v['value']},  // {v['doc']}"[:118] for v in e.values] + ["};"]
    for g in flags.values():
        out += [""] + comment(g["doc"])
        out += [f"inline constexpr {TYPES[g['type']]} {upper(g['name'])}_{upper(v['name'])} = {v['value']};" for v in g["values"]]
    for r in records.values():
        out += struct(r.name, r.doc, r.fields)
    for b in blocks:
        if b.kind == "seqlock":
            out += struct(b.name, b.doc, b.fields)
    out += ["", "// Where each block and each plain word is, from the board's first byte.", "namespace at", "{"]
    for b in blocks:
        out.append(f"inline constexpr std::size_t {upper(b.name)} = {b.offset};  // {b.size} bytes, {b.kind}")
    for b in blocks:
        if b.kind == "plain":
            out += [f"inline constexpr std::size_t {upper(b.name)}_{upper(f.name)} = {b.offset + f.offset};" for f in b.fields]
        if b.kind == "ring":
            out += [f"inline constexpr std::size_t {upper(b.name)}_SLOTS = {b.slots};",
                    f"inline constexpr std::size_t {upper(b.name)}_SLOT = {b.record.size};",
                    f"inline constexpr std::size_t {upper(b.name)}_FIRST = {b.offset + b.slots_at};"]
    out += ["}  // namespace at", "", "// A ring's event: read, not written yet (or being written), or overwritten by a newer one.",
            "enum class Read", "{", "  Ok,", "  NotYet,", "  Lost,", "};", ""]
    out += view(blocks, records)
    out += [f"}}  // namespace {ns}", ""]
    return "\n".join(out)


def plain_members(b):
    out = []
    out += comment(f"{b.name} ({b.writer} writes): single words.", "  ")
    for f in b.fields:
        t = f.enum or TYPES[f.type]
        load = load_field(f, f"at::{upper(b.name)}", "std::memory_order_acquire", "v")
        store = store_field(f, f"at::{upper(b.name)}", "std::memory_order_release", "v")
        out += [f"  {t} {b.name}{f.name}() const", "  {", f"    {t} v{{}};"] + indent(load) + ["    return v;", "  }",
                f"  void Set{b.name}{f.name}({t} v)", "  {"] + indent(store) + ["  }"]
    return out


def seqlock_members(b):
    relaxed = "std::memory_order_relaxed"
    out = []
    base = f"at::{upper(b.name)}"
    out += comment(f"{b.name} ({b.writer} writes): as one group. The writer alone calls Write.", "  ")
    out += [f"  void Write{b.name}(const {b.name}& v)", "  {", f"    std::atomic_ref<std::uint32_t> seq = Ref<std::uint32_t>({base});",
            f"    const std::uint32_t s = seq.load({relaxed}) & ~1u;", f"    seq.store(s + 1, {relaxed});",
            "    std::atomic_thread_fence(std::memory_order_release);"]
    for f in b.fields:
        out += indent(store_field(f, base, relaxed, f"v.{f.snake}"))
    out += ["    seq.store(s + 2, std::memory_order_release);", "  }",
            f"  // False when every try met the writer at work (or the board was never written: Seq 0 reads as written).",
            f"  bool Read{b.name}({b.name}* out, int tries = 64) const", "  {",
            f"    const std::atomic_ref<std::uint32_t> seq = Ref<std::uint32_t>({base});",
            "    for (int t = 0; t < tries; ++t)", "    {",
            "      const std::uint32_t s = seq.load(std::memory_order_acquire);", "      if (s & 1)", "        continue;",
            f"      {b.name} v;"]
    for f in b.fields:
        out += indent(load_field(f, base, relaxed, f"v.{f.snake}"), "      ")
    out += ["      std::atomic_thread_fence(std::memory_order_acquire);",
            f"      if (seq.load({relaxed}) == s)", "      {", "        *out = v;", "        return true;", "      }", "    }",
            "    return false;", "  }"]
    return out


def ring_members(b):
    relaxed = "std::memory_order_relaxed"
    out = []
    r, name = b.record, b.name
    slot = f"at::{upper(name)}_FIRST + number % at::{upper(name)}_SLOTS * at::{upper(name)}_SLOT"
    out += comment(f"{name} ({b.writer} writes): a ring of {b.slots} {r.name} records. Head: how many were written. "
                   "Numbers are the writers' to hand out (several writers may write, each its own numbers).", "  ")
    out += [f"  std::uint64_t {name}Head() const", "  {",
            f"    return Ref<std::uint64_t>(at::{upper(name)}).load(std::memory_order_acquire);", "  }",
            f"  void Write{name}(std::uint64_t number, const {r.name}& v)", "  {", f"    const std::size_t base = {slot};",
            "    std::atomic_ref<std::uint32_t> seq = Ref<std::uint32_t>(base);",
            "    const auto word = static_cast<std::uint32_t>(number * 2 + 2);",
            f"    seq.store(word - 1, {relaxed});", "    std::atomic_thread_fence(std::memory_order_release);"]
    for f in r.fields[1:]:
        out += indent(store_field(f, "base", relaxed, f"v.{f.snake}"))
    out += ["    seq.store(word, std::memory_order_release);",
            f"    std::atomic_ref<std::uint64_t> head = Ref<std::uint64_t>(at::{upper(name)});",
            f"    std::uint64_t h = head.load({relaxed});",
            f"    while (h < number + 1 && !head.compare_exchange_weak(h, number + 1, std::memory_order_release, {relaxed}))",
            "    {", "    }", "  }",
            f"  Read Read{name}(std::uint64_t number, {r.name}* out, int tries = 64) const", "  {",
            f"    const std::size_t base = {slot};",
            "    const std::atomic_ref<std::uint32_t> seq = Ref<std::uint32_t>(base);",
            "    const auto word = static_cast<std::uint32_t>(number * 2 + 2);",
            "    for (int t = 0; t < tries; ++t)", "    {",
            "      const std::uint32_t s = seq.load(std::memory_order_acquire);",
            "      const auto ahead = static_cast<std::int32_t>(s - word);",
            "      if (ahead > 0)", "        return Read::Lost;", "      if (ahead < -1)", "        return Read::NotYet;",
            "      if (ahead == -1)", "        continue;  // (being written)", f"      {r.name} v;", "      v.seq = s;"]
    for f in r.fields[1:]:
        out += indent(load_field(f, "base", relaxed, f"v.{f.snake}"), "      ")
    out += ["      std::atomic_thread_fence(std::memory_order_acquire);",
            f"      if (seq.load({relaxed}) == s)", "      {", "        *out = v;", "        return Read::Ok;", "      }", "    }",
            "    return Read::NotYet;", "  }"]
    return out


def view(blocks, records):
    out = ["// The board's memory (the mapping's first byte; aligned to 8 at least). Holds no state of its own: copy it freely.",
           "class View", "{", "public:", "  explicit View(void* base) : m_at(static_cast<unsigned char*>(base)) {}", "",
           "  // The launcher's side of the header, on a board of zeros: made for this version. The magic goes last.",
           "  void Make(std::uint32_t launcher_pid)", "  {", "    SetHeaderSize(static_cast<std::uint32_t>(SIZE));",
           "    SetHeaderVersion(VERSION);", "    SetHeaderLauncherPid(launcher_pid);", "    SetHeaderMagic(MAGIC);", "  }",
           "  enum class Taken", "  {", "    Ok,", "    NotABoard,     // no magic: nothing is written", 
           "    OtherVersion,  // the launcher's version is not this one", "    TooSmall,      // the file or the launcher's size is under SIZE",
           "  };",
           "  // The game's side: takes a board of its own version, or says why not. Unless it is no board at all, the game's",
           "  // version, size and process id go into the header either way, so that the launcher can say what refused it.",
           "  // `mapped`: the bytes the mapping really has.",
           "  Taken Take(std::uint32_t runner_pid, std::size_t mapped)", "  {",
           "    if (mapped < at::HEADER + 32 || HeaderMagic() != MAGIC)", "      return Taken::NotABoard;",
           "    SetHeaderRunnerSize(static_cast<std::uint32_t>(SIZE));", "    SetHeaderRunnerPid(runner_pid);",
           "    SetHeaderRunnerVersion(VERSION);", "    if (HeaderVersion() != VERSION)", "      return Taken::OtherVersion;",
           "    if (HeaderSize() < SIZE || mapped < SIZE)", "      return Taken::TooSmall;", "    return Taken::Ok;", "  }", ""]
    members = {"plain": plain_members, "seqlock": seqlock_members, "ring": ring_members}
    for b in blocks:
        out += members[b.kind](b) + [""]
    out += ["private:", "  template <typename T>", "  std::atomic_ref<T> Ref(std::size_t at) const",
            "  {", "    return std::atomic_ref<T>(*reinterpret_cast<T*>(m_at + at));", "  }",
            "  template <typename T>", "  T Load(std::size_t at, std::memory_order order) const", "  {",
            "    return Ref<T>(at).load(order);", "  }", "  template <typename T>",
            "  void Store(std::size_t at, T v, std::memory_order order)", "  {", "    Ref<T>(at).store(v, order);", "  }",
            "  static void Unpack(std::uint32_t word, std::uint8_t* to)", "  {",
            "    for (int i = 0; i < 4; ++i)", "      to[i] = static_cast<std::uint8_t>(word >> (8 * i));", "  }",
            "  static std::uint32_t Pack(const std::uint8_t* from)", "  {",
            "    return std::uint32_t{from[0]} | std::uint32_t{from[1]} << 8 | std::uint32_t{from[2]} << 16 | std::uint32_t{from[3]} << 24;",
            "  }"]
    for r in records.values():
        out += [f"  void Load{r.name}(std::size_t base, {r.name}* v, std::memory_order order) const", "  {"]
        for f in r.fields:
            out += indent(load_field(f, "base", "order", f"v->{f.snake}"), "    ")
        out += ["  }", f"  void Store{r.name}(std::size_t base, const {r.name}& v, std::memory_order order)", "  {"]
        for f in r.fields:
            out += indent(store_field(f, "base", "order", f"v.{f.snake}"), "    ")
        out += ["  }"]
    out += ["", "  unsigned char* m_at;", "};", ""]
    out += [f"static_assert(at::{upper(b.name)} % 8 == 0);" for b in blocks]
    out += [f"static_assert(sizeof(float) == 4 && {SIZES['f32']} == 4);"]
    return out
